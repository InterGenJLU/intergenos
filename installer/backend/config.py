def set_timezone(target, timezone="UTC"):
    """Set timezone via /etc/localtime symlink."""
    localtime = Path(target) / "etc" / "localtime"
    zoneinfo = Path(target) / "usr" / "share" / "zoneinfo" / timezone

    if localtime.exists() or localtime.is_symlink():
        localtime.unlink()

    if zoneinfo.exists():
        localtime.symlink_to(f"/usr/share/zoneinfo/{timezone}")
    else:
        # The requested zone is missing from the target's zoneinfo — surface it
        # instead of silently shipping UTC. This is the class that hid the
        # glibc-core zoneinfo-staging gap (the install passed with the clock on
        # UTC and no signal); never fall back silently.
        LOG.warning("set_timezone: %r not found under %s/usr/share/zoneinfo — "
                    "falling back to UTC; the installed clock will be UTC, not "
                    "%r", timezone, target, timezone)
        localtime.symlink_to("/usr/share/zoneinfo/UTC")


AI_PANEL_EXTENSION_UUID = "intergen@intergenos.org"


def _augment_enabled_extensions_override(override_text, add_uuid):
    """Given the text of the 91 enabled-extensions gschema override, return the
    text for a higher-priority override that adds add_uuid to enabled-extensions.

    Returns the new override text, or None if the source has no parseable
    enabled-extensions line or add_uuid is already present (nothing to do).
    Pure (no I/O) so the list parse/merge is unit-testable.
    """
    import ast
    for line in override_text.splitlines():
        s = line.strip()
        if s.startswith("enabled-extensions="):
            try:
                lst = ast.literal_eval(s.split("=", 1)[1].strip())
            except (ValueError, SyntaxError):
                return None
            if not isinstance(lst, (list, tuple)) or add_uuid in lst:
                return None
            lst = list(lst) + [add_uuid]
            arr = "[" + ", ".join("'%s'" % e for e in lst) + "]"
            return "[org.gnome.shell]\nenabled-extensions=%s\n" % arr
    return None


def enable_ai_panel_extension(target):
    """Opt-in enable of the InterGen AI panel GNOME extension (D-010).

    The default 91_intergenos-extensions.gschema.override deliberately OMITS
    intergen@intergenos.org (AI is opt-in); when the user chooses AI at install,
    ship a higher-priority 95 override (gschema overrides are last-wins by
    filename) that adds it, derived from the 91 default list READ FROM THE TARGET
    so it stays in sync with whatever shipped. The caller must run
    glib-compile-schemas in the chroot afterward for the change to take effect.

    Returns True if the 95 override was written (recompile needed), False if
    skipped (source missing / extension already enabled by default).
    """
    schemas = Path(target) / "usr" / "share" / "glib-2.0" / "schemas"
    src = schemas / "91_intergenos-extensions.gschema.override"
    if not src.exists():
        LOG.warning("enable_ai_panel_extension: %s missing; cannot opt-in the "
                    "AI panel extension", src)
        return False
    new_text = _augment_enabled_extensions_override(
        src.read_text(), AI_PANEL_EXTENSION_UUID)
    if new_text is None:
        return False
    (schemas / "95_intergen-ai.gschema.override").write_text(
        "# Opt-in (D-010): the InterGen AI panel extension is enabled here\n"
        "# ONLY because InterGen AI was chosen at install time. Numbered above\n"
        "# 91 so it wins; derived from 91's list so it stays in sync.\n"
        + new_text)
    return True


