# S4 (security-review 2026-07-01): a glibc/POSIX locale name is strictly
# <lang>[_TERRITORY][.CODESET][@modifier] — only letters, digits, and the
# separators . _ @ - . The user-selected locale is interpolated into a root
# `bash -c` inside the target chroot (generate_locale -> run_chroot), so a
# name carrying shell metacharacters ("en_US.UTF-8; rm -rf /", backticks,
# $(...)) would break out of the localedef command into arbitrary root code.
# Positive allowlist (stronger than a metachar denylist) — every SUPPORTED
# glibc locale matches, so a non-match is malformed or hostile and is refused
# before it reaches the shell.
_VALID_LOCALE_NAME = re.compile(r"^[A-Za-z0-9._@-]+$")

# crypttab(5) option that keeps the root LUKS volume out of the shutdown
# transaction's early detach window. See generate_crypttab's docstring for
# the measured failure it removes.
ROOT_CRYPT_SHUTDOWN_OPT = "x-initrd.attach"

# The fields a target's os-release must carry for generate_os_release to treat
# it as the file intergenos-base-files ships. Absence means the packages phase
# did not deliver the package's identity file, not that the values defaulted.
OS_RELEASE_IDENTITY_FIELDS = ("NAME", "VERSION", "VERSION_ID", "PRETTY_NAME")


def generate_fstab(target, partitions):
    """Generate /etc/fstab — PARTUUID for plain installs, UUID-of-mapper for LUKS.

    Ratified boot design (2026-04-08/09 + reaffirmed 2026-04-10 FINAL +
    Q-INIT 2026-05-05/06): PARTUUID + rootwait + no-installed-system-
    initramfs for plain installs. The kernel reads PARTUUID from the
    partition table directly without needing userland blkid; that is the
    whole reason for choosing PARTUUID over filesystem UUID.

    LUKS opt-in (D-001) narrowing: when partitions["root_mapper"] is set,
    /etc/fstab references the unlocked filesystem UUID (NOT the underlying
    LUKS partition's PARTUUID; that PARTUUID points at the encrypted
    container which is not directly mountable). The FDE initramfs runs
    fde-init.sh which uses /etc/crypttab to unlock, then exposes
    /dev/mapper/cryptroot whose ext4 UUID this fstab entry references.

    B-041 (T0-2 sub-cluster 6): closes the install-time drift from the
    ratified image-time path (scripts/create-image.sh:148-150 + 177 emit
    PARTUUID). Pre-fix this file emitted root=UUID= for both plain and
    LUKS installs, which would have caused plain installs to halt at
    first boot with "VFS: Unable to mount root fs" — no initramfs means
    no userland blkid means kernel can't resolve filesystem UUID.
    """
    fstab_path = Path(target) / "etc" / "fstab"
    fstab_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# /etc/fstab — InterGenOS",
        "# Generated by InterGenOS installer",
        "# <file system>  <mount point>  <type>  <options>         <dump>  <pass>",
    ]

    # Root entry: LUKS uses unlocked-mapper filesystem UUID; plain uses
    # PARTUUID of the partition holding the filesystem.
    if partitions.get("root_mapper"):
        root_mapper = partitions["root_mapper"]
        root_uuid = _get_uuid(root_mapper)
        if root_uuid:
            lines.append(f"UUID={root_uuid}  /              ext4    defaults          1       1")
        else:
            lines.append(f"{root_mapper}  /              ext4    defaults          1       1")
    else:
        root_partuuid = _get_partuuid(partitions["root"])
        if root_partuuid:
            lines.append(f"PARTUUID={root_partuuid}  /              ext4    defaults          1       1")
        else:
            lines.append(f"{partitions['root']}  /              ext4    defaults          1       1")

    # EFI System Partition — PARTUUID per ratified boot design (firmware
    # reads partition table directly; PARTUUID is the canonical key).
    # umask=0077 hides ESP contents from non-root users (signing keys may
    # be staged here transiently during signed-boot updates).
    if partitions.get("efi") and partitions.get("esp"):
        esp_partuuid = _get_partuuid(partitions["esp"])
        if esp_partuuid:
            lines.append(f"PARTUUID={esp_partuuid}  /boot/efi      vfat    umask=0077        0       2")
        else:
            lines.append(f"{partitions['esp']}  /boot/efi      vfat    umask=0077        0       2")

    fstab_path.write_text("\n".join(lines) + "\n")


ACCOUNT_DATABASES = ("passwd", "group", "shadow", "gshadow")
ACCOUNT_SKEL_REL = "usr/share/intergenos-base-files/account-skel"
_ACCOUNT_DB_MODES = {"passwd": 0o644, "group": 0o644, "shadow": 0o640, "gshadow": 0o640}


def seed_account_databases(target):
    """Create the target's account databases from the shipped skeleton.

    intergenos-base-files ships passwd/group/shadow/gshadow as reference data
    under /usr/share, NOT as /etc payload (decided 2026-07-24): when they were
    ordinary payload, installing the package on a system that had never had it
    deployed the pristine skeleton over the live databases and lost every real
    account. Nothing now writes those four paths as part of a package deploy,
    so the install has to create them explicitly — and this is the right layer
    for it, since initial account state is install-time state (build-rules
    §2.7: install-time decisions are written by the installer, not routed
    through a package).

    Ordering is load-bearing, and on any target that received packages the
    effective seed happens EARLIER than this call. pkm's canonical
    account-skel-seed hook (pkm/hooks.py, CANONICAL_HOOKS_PRE) runs the same
    create-only helper during the package phase, immediately ahead of the
    first systemd-sysusers run — which is the only point at which a seed can
    still act, because sysusers creates the databases itself from its declared
    entries and the helper never rewrites a database that exists. Measured on
    a fresh install before that hook existed: the config-phase call found all
    four already present and the skeleton's bin/sys/daemon accounts were
    absent for the life of the system.

    This call is retained as an idempotent belt for the path where no package
    install wrote the databases at all, and because the users phase's
    `useradd --root` immediately downstream cannot run without them. It is a
    no-op whenever the hook has already acted.

    A recipe post_install hook could not serve either role — those run in the
    hooks phase, later still than this one.

    CREATE-ONLY, like the shipped helper it mirrors: a database that already
    exists is left exactly as found. On a fresh install none exist and all four
    are created; the guard matters for a re-run over a populated target, where
    silently rewriting them would be the very loss this split exists to stop.

    Returns:
        dict with "seeded" and "kept" lists of database names.

    Raises:
        FileNotFoundError: the skeleton is absent from the target, which means
            base-files did not land — fail loudly rather than leave a system
            with no account databases at all.
    """
    target_path = Path(target)
    skel = target_path / ACCOUNT_SKEL_REL
    if not skel.is_dir():
        raise FileNotFoundError(
            f"account skeleton missing at {skel} — intergenos-base-files ships "
            f"it; a target without it did not receive the package"
        )

    etc = target_path / "etc"
    etc.mkdir(parents=True, exist_ok=True)
    seeded, kept = [], []
    for db in ACCOUNT_DATABASES:
        src = skel / db
        if not src.is_file():
            raise FileNotFoundError(f"account skeleton incomplete: {src} missing")
        dest = etc / db
        if dest.exists():
            kept.append(db)
            continue
        shutil.copyfile(src, dest)
        os.chmod(dest, _ACCOUNT_DB_MODES[db])
        try:
            os.chown(dest, 0, 0)
        except PermissionError:
            # Unprivileged test/dry runs: content is what matters here, and a
            # real install runs as root. Not silently ignored — the caller's
            # trace records the outcome either way.
            pass
        seeded.append(db)
    return {"seeded": seeded, "kept": kept}


def generate_hostname(target, hostname):
    """Generate /etc/hostname and /etc/hosts."""
    etc = Path(target) / "etc"
    etc.mkdir(parents=True, exist_ok=True)

    (etc / "hostname").write_text(f"{hostname}\n")

    hosts = (
        f"# /etc/hosts — InterGenOS\n"
        f"\n"
        f"127.0.0.1    localhost\n"
        f"127.0.1.1    {hostname}.localdomain {hostname}\n"
        f"::1          localhost ip6-localhost ip6-loopback\n"
        f"ff02::1      ip6-allnodes\n"
        f"ff02::2      ip6-allrouters\n"
    )
    (etc / "hosts").write_text(hosts)


def generate_locale(target, locale="en_US.UTF-8"):
    """Generate /etc/locale.conf AND compile the locale into the target glibc.

    C-010 + J-026 combined fix: previously only wrote /etc/locale.conf, which
    pointed LANG at a locale that didn't exist on the target — glibc-core/
    build.sh:69-74 bakes only C.UTF-8 / en_US / en_US.UTF-8, so any other
    user-picked locale (fr_FR.UTF-8, de_DE.UTF-8, ja_JP.UTF-8, ...) silently
    fell back to C at every login.

    Fix: after writing /etc/locale.conf, invoke localedef in the target chroot
    to compile the locale into /usr/lib/locale/<locale>/ on the installed
    system. localedef parses the locale name as <base>.<encoding> (e.g.
    "fr_FR.UTF-8" → base="fr_FR" + encoding="UTF-8") and reads the matching
    locale definition file under /usr/share/i18n/locales/ + the charmap under
    /usr/share/i18n/charmaps/.

    Skipped for locales without an encoding suffix (C, POSIX, single-name)
    — these are always-present in the glibc-core baked set; localedef would
    fail with "cannot read character map" since they don't have a separate
    encoding step.

    Skipped for malformed locale strings (empty base or encoding after the
    partition) — locale.conf is still written so the user can hand-fix
    post-install, but localedef gets garbage input on malformed names.

    Orchestrator owns virtual_fs lifecycle (C-006); this runs during
    PHASE_CONFIG which is between PHASE_VIRTUAL_FS and PHASE_CLEANUP, so
    the chroot is mountable.
    """
    from .hooks import run_chroot

    # S4 fix — validate the user-selected locale BEFORE it is written or reaches
    # the root chroot shell. run_chroot execs `bash -c "<cmd>"`, and localedef's
    # argv below interpolates `locale`/`base`/`encoding` verbatim; a name with
    # shell metacharacters would inject arbitrary root commands into the target.
    # Fail-closed: refuse a non-allowlisted name outright (never persist a
    # poisoned locale.conf, never touch the shell) — the validation cannot live
    # in run_chroot itself because other callers (bootloader) legitimately pass
    # shell syntax, so the input must be gated where the untrusted value enters.
    if not _VALID_LOCALE_NAME.match(locale):
        raise ValueError(
            f"refusing to configure an invalid locale name {locale!r}: a locale "
            "must be <lang>[_TERRITORY][.CODESET][@modifier] "
            "(letters, digits, and . _ @ - only)")

    etc = Path(target) / "etc"
    (etc / "locale.conf").write_text(f"LANG={locale}\n")

    # C / POSIX / single-name locale — always-present in baked set; nothing
    # to compile. localedef would fail with "cannot read character map".
    if "." not in locale:
        return

    base, _, encoding = locale.partition(".")
    if not base or not encoding:
        # Malformed locale string ("foo.", ".bar", ".") — locale.conf
        # already written; don't run localedef on garbage.
        return

    cmd = f"localedef -i {base} -f {encoding} {locale}"
    rc, stdout, stderr = run_chroot(str(target), cmd)
    if rc != 0:
        raise RuntimeError(
            f"localedef failed for locale {locale!r} "
            f"(base={base!r}, encoding={encoding!r}): "
            f"{(stderr or '').strip()}"
        )


