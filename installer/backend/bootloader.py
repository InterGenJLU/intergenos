# `efibootmgr` plain-output format. Each entry is:
#   Boot<HHHH><star_or_space> <label><TAB-OR-2+SPACES><path>
# Active entries have `*` after the bootnum; inactive have a space.
# Real efibootmgr 18+ uses a tab between label and path; older versions
# and some test fixtures use 2-or-more spaces. The label terminator
# accepts either form for resilience. Label runs until the terminator;
# path runs to end-of-line.
_EFIBOOTMGR_LINE_RE = re.compile(
    r"^Boot([0-9A-Fa-f]{4})[*\s]\s+(.+?)(?:\t|  +|$)"
)

# Fuller entry parse for the default-boot-target decision (D1 / work-plan 1.25):
# captures the active flag (`*`) and the trailing device path in addition to the
# bootnum + label. The path is what lets us tell an installed-OS entry (lives on
# a hard-disk partition -> `HD(...)` in the path) apart from firmware-synthesized
# removable/network/setup entries (`USB(...)`, `MAC(...)`, `Fv(...)`), so a
# single-OS machine's stock NVRAM noise never reads as "another OS is present".
_EFIBOOTMGR_ENTRY_RE = re.compile(
    r"^Boot([0-9A-Fa-f]{4})(\*?)\s+(.+?)(?:(?:\t|  +)(.*))?$"
)
_EFIBOOTMGR_ORDER_RE = re.compile(r"^BootOrder:\s*(.+)$")


def _parse_efibootmgr_output(stdout):
    """Parse `efibootmgr` plain output into (boot_order, entries).

    boot_order: list of bootnum strings in BootOrder, or [] if no BootOrder line.
    entries: {bootnum: (active: bool, label: str, path: str)}.
    """
    order = []
    entries = {}
    for line in stdout.splitlines():
        mo = _EFIBOOTMGR_ORDER_RE.match(line)
        if mo:
            order = [b.strip() for b in mo.group(1).split(",") if b.strip()]
            continue
        me = _EFIBOOTMGR_ENTRY_RE.match(line)
        if me:
            bootnum, star, label, path = me.groups()
            entries[bootnum] = (star == "*", label.strip(), (path or "").strip())
    return order, entries


# Device-path nodes that mark a boot entry as REMOVABLE/ephemeral media, not
# an installed-on-disk OS. A USB stick's firmware-synthesized entry can carry
# a trailing HD(...) partition node (ASRock X870, ge9b-04 dogfood install:
# `...USB(1,0)/USB(0,0)/HD(2,GPT,...)` for the install stick itself), so the
# bare HD(...) test misclassified the install medium as a foreign OS
# (PI-ge9b04-B). Any of these nodes ANYWHERE in the path disqualifies the
# entry — the partition node's presence does not make removable media an
# installed OS.
_REMOVABLE_PATH_NODES = ("USB(", "USBClass(", "USBWWID(", "SD(", "eMMC(",
                         "CDROM(")


def _foreign_os_bootnums(entries, our_label):
    """Bootnums of ACTIVE, installed-on-disk boot entries that are not ours.

    An installed OS registers a boot entry whose device path is a hard-disk
    partition (`HD(...)`). Firmware-synthesized removable/network/setup entries
    are excluded — but NOT by assuming they lack `HD(...)`: removable-media
    entries can carry a partition node at the tail (see _REMOVABLE_PATH_NODES),
    so any removable node in the path disqualifies the entry first. This keeps
    the set to "another operating system is installed here" — the only case
    where making InterGenOS the default silently displaces a real prior
    default (the D1 user-control concern).
    """
    out = []
    for bootnum, (active, label, path) in entries.items():
        if not active or label == our_label:
            continue
        if any(node in path for node in _REMOVABLE_PATH_NODES):
            continue
        if "HD(" in path:
            out.append(bootnum)
    return out


def has_other_os_boot_entries():
    """Confirm-time probe (live host, not chroot): does UEFI NVRAM already hold
    another installed OS's boot entry?

    Returns True (a foreign on-disk OS entry is present -> the frontend asks
    whether InterGenOS should become the default), False (none — single-OS, keep
    the current prepend, no ask), or None (not EFI / efibootmgr unavailable /
    unreadable — undeterminable, so the frontend asks nothing and the backend
    keeps its safe default of prepending). Mirrors secureboot.is_secure_boot_
    enabled()'s tri-state None-means-unknown contract.
    """
    try:
        res = subprocess.run(
            ["efibootmgr"], capture_output=True, text=True,
        )
    except (FileNotFoundError, OSError):
        return None
    if res.returncode != 0:
        return None
    _order, entries = _parse_efibootmgr_output(res.stdout)
    return bool(_foreign_os_bootnums(entries, BOOTLOADER_ID))


def _apply_default_boot_choice(target, make_default_boot, foreign_before):
    """Honor the user's default-boot-target choice after efibootmgr --create.

    --create prepends the new InterGenOS entry to BootOrder, making it the
    machine default. That is correct for a single-OS install (nothing to
    respect) and when the user asked for it, but on multi-OS metal a user who
    declined must keep their prior default. When foreign OS entries existed
    before install AND make_default_boot is False, move InterGenOS to the END of
    BootOrder so the previously-first (foreign) entry stays the default. Always
    emits a trace line recording the decision.

    Fail-open: if the post-create NVRAM state can't be read or InterGenOS isn't
    already first, leave BootOrder as --create left it (never strand the machine
    trying to be polite).
    """
    if not foreign_before or make_default_boot:
        trace.trace_event(
            "efibootmgr_default_boot_target",
            make_default=make_default_boot,
            foreign_entries_present=bool(foreign_before),
            action="kept efibootmgr --create prepend (InterGenOS is the default)",
            intent="single-OS install or user asked to be the default boot "
                   "target -> InterGenOS stays first in BootOrder (D1/1.25)",
        )
        return

    order, entries = _parse_efibootmgr_output(
        trace.traced_run_chroot(target, "efibootmgr")[1]
    )
    our = next(
        (b for b, (_a, label, _p) in entries.items() if label == BOOTLOADER_ID),
        None,
    )
    if our is None or not order or order[0] != our:
        trace.trace_event(
            "efibootmgr_default_boot_target",
            make_default=False,
            foreign_entries_present=True,
            action="left BootOrder unchanged (InterGenOS not first, or order "
                   "unreadable — nothing to demote)",
            intent="user declined default but the post-create order did not "
                   "need adjusting / could not be read (fail-open)",
        )
        return

    new_order = [b for b in order if b != our] + [our]
    trace.traced_run_chroot(target, f"efibootmgr -o {','.join(new_order)}")
    trace.trace_event(
        "efibootmgr_default_boot_target",
        make_default=False,
        foreign_entries_present=True,
        action=f"demoted InterGenOS to last in BootOrder ({','.join(new_order)})",
        intent="user declined making InterGenOS the default on a multi-OS "
               "machine -> prior default preserved as first (D1/1.25, Prime "
               "Directive: do not silently take over the machine's boot default)",
    )


def _verify_bootorder_end_state(target, expect_default):
    """Read NVRAM back after the boot-entry write and record what it holds.

    Everything before this point states an intent: `efibootmgr --create`
    prepends our entry, and _apply_default_boot_choice reorders when the user
    declined. Neither result was ever read back, so a firmware that accepts
    the write and then presents a different BootOrder went unnoticed — which
    is exactly what a UEFI 2.110 AMI board did on 2026-07-31: the install
    trace showed InterGenOS first, and the installed system came up with
    `BootOrder: 0001,0000`, 0001 being the firmware's own "UEFI OS" entry for
    \\EFI\\BOOT\\BOOTX64.EFI on the same ESP. Both entries reach the same
    partition, so the machine boots — through the removable-media fallback
    loader instead of the registered one.

    This is a report, not a gate: the install must not fail because a
    firmware reorders NVRAM, and the boot-time checker
    (intergenos-bootorder-check) is what repairs it on the installed system.
    What this adds is the checked fact — the trace now carries the observed
    end state instead of an assumption.
    """
    rc, stdout, _stderr = trace.traced_run_chroot(target, "efibootmgr")
    if rc != 0:
        trace.trace_event(
            "efibootmgr_bootorder_verified",
            verified=False,
            reason="post-write efibootmgr read failed",
            rc=rc,
            intent="read NVRAM back after registering the boot entry; the "
                   "read itself failed, so the end state is undetermined "
                   "(not a pass and not a failure)",
        )
        return

    order, entries = _parse_efibootmgr_output(stdout)
    ours = [b for b, (_a, label, _p) in entries.items()
            if label == BOOTLOADER_ID]
    first_is_ours = bool(order) and order[0] in ours
    trace.trace_event(
        "efibootmgr_bootorder_verified",
        verified=True,
        boot_order=",".join(order),
        our_bootnums=",".join(sorted(ours)),
        expected_first=bool(expect_default),
        observed_first_is_ours=first_is_ours,
        matches_intent=(first_is_ours == bool(expect_default)),
        intent="record the BootOrder the firmware actually holds after the "
               "boot-entry write, so a firmware that reorders NVRAM is "
               "visible in the install trace rather than discovered later "
               "on the booted system",
    )


def _write_boot_default_intent(target, expect_default, foreign_before):
    """Record on the target whether InterGenOS is meant to boot by default.

    The boot-time checker reads this file. Without it the checker cannot
    tell "the firmware demoted us" from "the user chose another OS as the
    default", and repairing the second case would take the machine over
    behind the user's back.

    Written for every EFI install, including one whose efibootmgr call
    failed — the intent is what this install meant, independent of whether
    NVRAM accepted it.
    """
    path = Path(target) / BOOT_DEFAULT_INTENT_REL
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            "# /etc/intergenos/boot-default.conf — InterGenOS\n"
            "# Written by the installer. Read by "
            "intergenos-bootorder-check.service.\n"
            "# default_boot_target=yes  -> the checker restores InterGenOS to\n"
            "#   the front of BootOrder when firmware moves it.\n"
            "# default_boot_target=no   -> the user kept another operating\n"
            "#   system as the default; the checker only reports.\n"
            f"default_boot_target={'yes' if expect_default else 'no'}\n"
            f"boot_entry_label={BOOTLOADER_ID}\n"
            f"foreign_os_entries_at_install={len(foreign_before)}\n"
        )
        path.chmod(0o644)
    except OSError as exc:
        # Never fail an install over the record file; the checker treats an
        # absent file as "no recorded intent" and takes no action.
        trace.trace_event(
            "boot_default_intent_write_failed",
            path=str(path), error=str(exc),
            intent="record the default-boot-target decision for the boot-time "
                   "checker; the write failed, so the checker will find no "
                   "recorded intent and will only report",
        )
        logger.warning("could not write %s: %s", path, exc)
        return

    trace.trace_event(
        "boot_default_intent_recorded",
        path=f"/{BOOT_DEFAULT_INTENT_REL}",
        default_boot_target=("yes" if expect_default else "no"),
        foreign_os_entries_at_install=len(foreign_before),
        intent="record the install-time default-boot-target decision so the "
               "boot-time BootOrder checker repairs only what this install "
               "actually intended",
    )


def _cleanup_stale_efi_entries(target, label):
    """Delete every existing UEFI boot entry matching `label` before --create.

    Re-installing InterGenOS onto the same machine repeatedly accumulates
    stale `InterGenOS` entries in NVRAM — each install's `efibootmgr
    --create` adds a fresh entry without removing prior ones that point
    at GPT partition UUIDs of older installs. 2026-05-27 install #28
    trace surfaced five stale entries Boot000{2,3,4,5} alongside the
    newly-created Boot0006.

    Strategy: list current entries, find every BootNNNN* whose label
    matches `label` exactly, and `efibootmgr -b NNNN -B` each one.
    Then the caller's --create produces a single clean entry.

    Fail-open: if efibootmgr can't list (no efivars, read-only, etc.),
    skip cleanup — the subsequent --create will surface the underlying
    error with full context.
    """
    rc, stdout, _ = trace.traced_run_chroot(target, "efibootmgr")
    if rc != 0:
        # efibootmgr unavailable — likely no efivars (build VM) or
        # firmware-read failure. Let the --create that follows surface
        # the real error.
        return

    stale_bootnums = []
    for line in stdout.splitlines():
        m = _EFIBOOTMGR_LINE_RE.match(line)
        if m and m.group(2).strip() == label:
            stale_bootnums.append(m.group(1))

    if not stale_bootnums:
        return

    trace.trace_event(
        "efibootmgr_cleanup_stale",
        label=label,
        bootnums=stale_bootnums,
        count=len(stale_bootnums),
        intent="delete stale NVRAM entries with matching label before "
               "efibootmgr --create so re-installs don't accumulate "
               "duplicates (2026-05-27 install #28 anomaly D)",
    )

    for bootnum in stale_bootnums:
        trace.traced_run_chroot(
            target, f"efibootmgr -b {bootnum} -B",
        )


def _split_partition(part_dev):
    """Split a partition device path into disk + partition number.

    Examples:
        /dev/sda1       -> ('/dev/sda', 1)
        /dev/nvme0n1p2  -> ('/dev/nvme0n1', 2)
        /dev/mmcblk0p3  -> ('/dev/mmcblk0', 3)
    """
    if "nvme" in part_dev or "mmcblk" in part_dev:
        # NVMe/MMC use 'p' separator before partition number
        idx = part_dev.rfind("p")
        return part_dev[:idx], int(part_dev[idx + 1:])
    else:
        # SATA/SCSI use bare digit suffix
        i = len(part_dev)
        while i > 0 and part_dev[i - 1].isdigit():
            i -= 1
        return part_dev[:i], int(part_dev[i:])


