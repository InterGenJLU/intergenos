# A real block device, any family — destructive when written to by a redirect
# or an of= target: sd (SCSI/SATA), nvme, vd (virtio — every VM, including our
# own test beds), mmcblk (SD/eMMC), xvd (Xen), loop, dm- (device-mapper), md
# (md-raid). Deliberately NOT char devices (/dev/null, /dev/zero, /dev/tty,
# /dev/stdout, /dev/random) so ordinary redirects classify normally. Code review
# of 6c079275 surfaced that the prior sd/nvme-only rule let a redirect-wipe to a
# virtio/eMMC disk slip to CONFIRM instead of BLOCKED.
# Also /dev/disk/by-id|by-uuid|by-path|by-label — symlinks that all resolve to a
# real block device, so a redirect there is a redirect to the disk. Nothing
# legitimate redirects into /dev/disk/.
# And /dev/mapper/<name> — the device-mapper named volumes: the UNLOCKED LUKS
# root (`/dev/mapper/cryptroot`) and the dm-verity root (`/dev/mapper/igos-root`),
# plus the libdevmapper control node. `dm-` above only matches the anonymous
# `/dev/dm-N` alias; the security review found a redirect onto the named mapping
# (`> /dev/mapper/cryptroot`) — the plaintext view of the encrypted root — read as
# safe. Nothing legitimate redirects into /dev/mapper/, so the whole dir is blocked.
_BLOCK_DEVICE = r"/dev/(?:sd|nvme|vd|mmcblk|xvd|loop|dm-|md|mapper/|disk/)"
_BLOCK_DEVICE_REDIRECT = re.compile(r">\s*" + _BLOCK_DEVICE)

_BLOCKED_PATTERNS = [
    re.compile(r"\|\s*bash"),           # pipe to bash
    re.compile(r"\|\s*sh\b"),           # pipe to sh
    re.compile(r"\$\("),                # command substitution
    re.compile(r"`[^`]+`"),             # backtick execution
    _BLOCK_DEVICE_REDIRECT,             # redirect-wipe to any block device family
    re.compile(r">\s*/etc/"),           # write to system config
    re.compile(r">\s*/proc/"),          # write to proc
    re.compile(r">\s*/sys/"),           # write to sys
    re.compile(r"\brm\s+(-\S+\s+)*/\s*$"),  # rm [flags] /  (delete root itself)
    # Recursive-force rm at ANY path is BLOCKED (restores + widens the prior
    # run_command denylist, which blanket-blocked `rm -rf <anypath>`; my first
    # AI-4 pass narrowed this to `rm -rf /` only, a regression WC caught). A
    # recursive force delete is unrecoverable and must not auto/confirm-run from
    # the shell tool regardless of target. One pattern, two lookaheads: BLOCK
    # when an rm invocation carries BOTH a recursive flag (-r/-R, combined like
    # -rf/-Rf, or --recursive) AND a force flag (-f, combined, or --force), in
    # any order, combined or separate. rm without both (rm file, rm -f file,
    # rm -r dir) stays CONFIRM — this matches the old denylist's superset, no
    # over-block.
    # F4 correctness fix (2026-07-02): each lookahead requires the flag to be a
    # WHITESPACE-DELIMITED token (`.*\s(?:-…|--…)`), so a hyphenated FILENAME no
    # longer false-matches — the prior `.*(?:-[a-zA-Z]*[rR]…)` matched a dash
    # anywhere, so `rm my-report-final.txt` read `-report`/`-final` as flags and
    # was HARD-blocked. `\brm\b` (not `\brm\s+`) leaves the post-rm whitespace
    # unconsumed so the lookahead's `\s` can see the first real flag token; the
    # flag-letter alt keeps NO trailing `\b` so combined flags (`-rf`) still match.
    re.compile(
        r"\brm\b"
        r"(?=.*\s(?:-[a-zA-Z]*[rR]|--recursive))"
        r"(?=.*\s(?:-[a-zA-Z]*[fF]|--force))"
    ),
    re.compile(r":\(\)\{"),             # fork bomb
    re.compile(r">\s*/boot/"),          # write to boot partition
    re.compile(r"mkswap\s"),            # swap creation
    re.compile(r"swapon\s"),            # swap activation
    # AI-4 — absorbed from run_command's inline denylist so this is the one
    # strong classifier (a strict superset of every prior per-tool check):
    re.compile(r"\bmkfs\b"),                                   # mkfs.ext4 etc (suffix forms)
    re.compile(r"\bchmod\s+.*-R\s+777\s+/\s*$"),              # chmod -R 777 /
    re.compile(r"\bchown\s+.*-R\s+.*\s+/\s*$"),               # chown -R ... /
    re.compile(                                                # mask/disable a critical unit
        r"\bsystemctl\s+(mask|disable)\s+"
        r"(NetworkManager|dbus|systemd|polkit|ssh|sshd)"
    ),
]


# Shell operators that chain/compose multiple commands. A compound command is
# classified by its MOST dangerous SEGMENT, so a read-only prefix can never
# launder a destructive suffix (e.g. `echo yes | mkfs.ext4 /dev/sda1`). This must
# be a SUPERSET of what the shell actually honors — the security review found the
# old `| && ;` set under-modeled the shell, so a benign leading command could hide
# a destructive trailing one behind a separator the classifier did not split on.
# Full set: pipe `|`, or-list `||`, and-list `&&`, sequence `;`, background `&`,
# pipe-both `|&`, and a newline/carriage-return. Longest operators first so `||` /
# `|&` / `&&` win over their single-char prefixes. The background `&` alternative
# excludes redirect forms (`2>&1`, `>&2`, `&>file`) via look-around so a common
# fd-redirect is not mis-split. Kept in a CAPTURING group so re.split returns the
# operators too — that lets us tell a real PIPE (`|`/`|&`, which makes an adjacent
# pager a non-interactive data-sink) from `||`/`&&`/`;`/`&` (which do NOT: the
# security review found the old coarse `"|" in command` tripped on a logical-or).
_SHELL_SEP = re.compile(r"(\|\||\|&|&&|;|\||(?<![<>&])&(?![>&])|\n|\r)")
_PIPE_OPS = frozenset({"|", "|&"})
# Subshell / brace-group punctuation is peeled from each SEGMENT's ends (in
# _split_shell) so a grouped command (`(rm -rf x)`, `{ mount /y; }`) is classified
# by its own base token, not a leading `(`/`{` -- done per-segment (not a global
# strip) so an xargs replacement placeholder (`-I{}`) survives for the option-skip.

