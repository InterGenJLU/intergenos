def _sort_writes(parts: list[str]) -> bool:
    """True if a `sort` invocation writes a file via -o / --output.

    sort/uniq/cut are AUTO read-only stream filters, but `sort -o FILE` (and
    `--output`) WRITES a file — AUTO must mean cannot-mutate-regardless-of-args, so
    the write form is CONFIRM. The read-only pipeline form (`sort -rh`, no -o) stays
    AUTO, so the du|sort -rh|head disk-usage pipeline is unaffected.
    """
    for tok in parts[1:]:
        if tok in ("-o", "--output") or tok.startswith("--output="):
            return True
        # Short-flag cluster carrying the output flag (`-o`, `-ro`, `-ofile`): in a
        # sort short cluster 'o' can only be the output flag, which writes.
        if tok.startswith("-") and not tok.startswith("--") and "o" in tok[1:]:
            return True
    return False


def _uniq_writes(parts: list[str]) -> bool:
    """True if a `uniq` invocation names an OUTPUT file (a 2nd positional operand).

    uniq syntax is `uniq [OPTION]... [INPUT [OUTPUT]]` — a second non-option operand
    is an output file that gets WRITTEN, so it is CONFIRM, not AUTO. The short value
    flags -f/-s/-w consume a numeric next token when written separately; that value
    is skipped so it is not miscounted as an operand.
    """
    operands = 0
    skip_next = False
    for tok in parts[1:]:
        if skip_next:
            skip_next = False
            continue
        if tok.startswith("-") and tok != "-":
            if tok in ("-f", "-s", "-w"):
                skip_next = True
            continue
        operands += 1
    return operands >= 2


# find primaries that MUTATE or EXEC: -delete removes; -exec/-execdir and their
# interactive-confirm siblings -ok/-okdir run an arbitrary command; -fprint/-fprintf/
# -fls WRITE a named file. Plain read-only find (-name/-type/-mtime/-print/...) stays
# AUTO. (Destructive -exec rm -rf is already caught earlier by the rm-recursive-force
# BLOCKED pattern.)
_FIND_WRITE_FORMS = frozenset({
    "-delete", "-exec", "-execdir", "-ok", "-okdir",
    "-fprint", "-fprintf", "-fls",
})


def _find_mutates(parts: list[str]) -> bool:
    """True if a `find` invocation can mutate or exec (see _FIND_WRITE_FORMS)."""
    return any(tok in _FIND_WRITE_FORMS for tok in parts[1:])


# env's OWN options. The value-taking ones consume the next token; --opt=val carries
# its value inline. Everything after env + its options + NAME=VALUE assignments is the
# WRAPPED command, which carries the real tier.
_ENV_VALUE_FLAGS = frozenset({"-u", "-C", "--unset", "--chdir"})


def _dequote(s: str) -> str:
    """Strip all quote characters from a wrapped / re-entered command string.

    A real shell=True call legitimately quotes a wrapped command (`watch 'mount /x'`,
    `nohup "umount /y"`), which leaves a leading quote glued to the first token so
    `basename("'mount")` != `mount` and a recognition-tier BLOCKED inner softened to
    the unknown-command CONFIRM default (F2 correctness fix, 2026-07-02 — the same
    one-notch soften WC's methodology warned pattern-listed tests would mask). Every
    exec-wrapper extractor runs its wrapped rest through this before recursion, so the
    quoted and unquoted forms classify identically. Like the shell `-c` re-entry it is
    a SAFE over-approximation: removing quotes can only expose MORE tokens/segments to
    the worst-of scan (e.g. a separator that was quoted), never hide one.
    """
    return s.replace('"', " ").replace("'", " ").strip()


def _env_wrapped_command(parts: list[str]) -> str | None:
    """Return the command `env` wraps (after stripping env + its own options +
    NAME=VALUE assignments), or None for a bare env that only prints/sets the
    environment (no wrapped command). env is TRANSPARENT to the classifier: a
    read-only wrapped command stays AUTO, a write confirms, a dangerous one is
    refused. An unknown wrapped command falls to CONFIRM via the normal default —
    fail-safe.
    """
    i, n = 1, len(parts)
    while i < n:
        tok = parts[i]
        if tok == "--":
            i += 1
            break
        if tok in _ENV_VALUE_FLAGS:
            i += 2                                  # flag + its value token
            continue
        if tok.startswith("--") and "=" in tok:     # --unset=VAR / --chdir=DIR
            i += 1
            continue
        if tok.startswith("-") and tok != "-":      # other env option (e.g. -i, -0)
            i += 1
            continue
        if "=" in tok:                              # NAME=VALUE assignment
            i += 1
            continue
        break                                       # first real token = the command
    rest = parts[i:]
    return _dequote(" ".join(rest)) if rest else None


def _watch_wrapped_command(parts: list[str]) -> str | None:
    """Return the command `watch` runs on a loop (after stripping watch + its
    options), or None for a bare/optionless watch. Like env, watch is TRANSPARENT
    to the classifier: `watch free` is AUTO, `watch 'rm -rf x'` is BLOCKED --
    never a flat pass that launders the wrapped command past the gate.
    """
    i, n = 1, len(parts)
    while i < n:
        tok = parts[i]
        if tok == "--":
            i += 1
            break
        if tok in ("-n", "--interval") and i + 1 < n:   # interval flag + its value
            i += 2
            continue
        if tok.startswith("-") and tok != "-":          # other watch option (-d,-b,-g,-t,-c…)
            i += 1
            continue
        break                                            # first real token = wrapped command
    rest = parts[i:]
    return _dequote(" ".join(rest)) if rest else None


def _prefix_wrapped_command(parts: list[str]) -> str | None:
    """Return the command a transparent exec-prefix (`nohup`/`nice`/`timeout`/...)
    runs, after stripping the wrapper + its options + any leading positional arg
    (`timeout DURATION`), or None for a bare wrapper with nothing wrapped. The
    wrapped command carries the real tier, so a BLOCKED base command cannot hide
    behind the wrapper. Fail-safe: over-stripping yields None (bare wrapper -> AUTO,
    nothing runs); the pattern-based blocks catch destructive content regardless.
    """
    wrapper = os.path.basename(parts[0])
    value_flags, positionals = _PREFIX_SPECS[wrapper]
    i, n = 1, len(parts)
    while i < n:                                          # strip the wrapper's own options
        tok = parts[i]
        if tok == "--":
            i += 1
            break
        if tok.startswith("--") and "=" in tok:          # --long=value
            i += 1
            continue
        if tok in value_flags:                           # value-taking flag + its value
            # ...but never swallow a recognition-tier refuse as the "value" (a
            # malformed/optional-arg flag like `-I mount` or `--replace mount` must
            # still expose the command), same guard as the positional skip below.
            if i + 1 < n and os.path.basename(parts[i + 1]) in _POSITIONAL_STOP:
                i += 1
            else:
                i += 2
            continue
        if tok.startswith("-") and tok != "-":           # any other option (incl. -n5, -c2, --foreground)
            i += 1
            continue
        break
    for _ in range(positionals):                         # e.g. timeout DURATION / flock LOCK / taskset MASK
        if i < n and os.path.basename(parts[i]) not in _POSITIONAL_STOP:
            i += 1                                        # ...but never skip PAST a hidden blocked command
    rest = parts[i:]
    return _dequote(" ".join(rest)) if rest else None


# Value-taking shell options that precede -c with a SEPARATE-token value: the
# set-option (`-o vi` / `+o posix`), the shopt-enable (`-O extglob` / `+O …`), and
# the startup/init-file options (`--rcfile PATH` / `--init-file PATH`). Their value
# is not a script file and must be skipped, or the "first non-flag = script file"
# bailout mistakes it for one and the -c payload is never inspected (F1' fix,
# 2026-07-02, independent-red-team finding: `bash -o emacs -c 'mount /x'` softened
# to CONFIRM). +o/+O start with '+', so they are matched by membership, not by the
# leading-dash test.
_SHELL_VALUE_OPTS = frozenset({"-o", "+o", "-O", "+O", "--rcfile", "--init-file"})


def _shell_c_argument(parts: list[str]) -> str | None:
    """Return the command-string a shell/`script` runs via `-c` (`bash -c "…"`,
    `bash -lc "…"`), or None for a bare/script-file invocation with no inline `-c`.
    A short-flag bundle whose letters include `c` (e.g. `-lc`) counts. Everything
    after the `-c` token is rejoined (a naive split fragments the quoted string) and
    ALL quote characters removed -- an over-approximation (may include the shell's
    $0/$@ positionals and exposes any separator that was quoted) that is SAFE: it can
    only add segments/tokens to the worst-of scan downstream, never hide one.

    A value-taking shell option before -c (`-o vi`, `--rcfile PATH`) has its value
    skipped so the bailout below does not read that value as a script file and miss
    the -c payload (F1' fix, 2026-07-02).
    """
    skip_value = False
    for k, tok in enumerate(parts[1:], start=1):
        if skip_value:                                    # prior option's separate-token value
            skip_value = False
            continue
        if tok == "-c" or (
            tok.startswith("-") and not tok.startswith("--")
            and "c" in tok[1:] and "=" not in tok
        ):
            rest = parts[k + 1:]
            if not rest:
                return None
            return _dequote(" ".join(rest))
        if tok in _SHELL_VALUE_OPTS:                      # value-taking opt: skip it + its value
            skip_value = True
            continue
        if tok.startswith("--") and "=" in tok:           # --rcfile=PATH (inline value) -> not a script file
            continue
        if not tok.startswith("-"):                       # first non-flag = a script FILE, not a -c string
            return None
    return None


def _split_shell(command: str) -> list[tuple[str, bool]]:
    """Split a command into its shell segments, returning (segment, pipe_adjacent)
    for each non-empty segment. A compound command is classified by its worst
    segment; `pipe_adjacent` (a real `|`/`|&` on either side) is what makes an
    adjacent pager a non-interactive data-sink -- `||`/`&&`/`;`/`&` do NOT. Subshell
    / brace-group punctuation is stripped from each segment's ENDS (so `(rm -rf x)`
    and `{ mount /y; }` classify by their inner base token) but NOT mid-token, so an
    xargs replacement placeholder (`-I{}`) is preserved for the wrapper option-skip.
    A single simple command returns one segment (itself, pipe_adjacent = False).
    """
    tokens = _SHELL_SEP.split(command)                    # [seg, op, seg, op, ..., seg]
    segments = tokens[0::2]
    ops = tokens[1::2]                                     # len == len(segments) - 1
    result: list[tuple[str, bool]] = []
    for j, seg in enumerate(segments):
        seg = seg.strip().strip("(){}").strip()           # peel grouping at the ENDS only
        if not seg:
            continue
        before = ops[j - 1] if j - 1 >= 0 else None
        after = ops[j] if j < len(ops) else None
        piped = before in _PIPE_OPS or after in _PIPE_OPS
        result.append((seg, piped))
    return result


def classify_command(command: str, _piped: bool = False) -> SafetyTier:
    """Classify a shell command into a safety tier.

    This is the single strong classifier for shell commands (AI-4): it is a
    strict superset of the per-tool inline checks that previously lived in
    run_command — base-command blocks, destructive-pattern blocks, compound
    decomposition, and the AUTO/CONFIRM tables. run_command delegates here so
    there is one classifier to audit, with no weaker second copy.

    Args:
        command: The shell command string to classify.

    Returns:
        SafetyTier.AUTO, SafetyTier.CONFIRM, or SafetyTier.BLOCKED
    """
    command = command.strip()
    if not command:
        return SafetyTier.BLOCKED

    for pattern in _BLOCKED_PATTERNS:
        if pattern.search(command):
            logger.warning("Command blocked by pattern: %s", command[:80])
            return SafetyTier.BLOCKED

    # Compound command: classify by the worst SEGMENT so a benign segment cannot
    # mask a dangerous one. Done AFTER the whole-string pattern scan (which catches
    # pipe-to-shell + redirect patterns that only exist at the full-command level).
    # _split_shell models a SUPERSET of the shell's separators and reports, per
    # segment, whether a REAL pipe (`|`/`|&`) makes it a non-interactive data-sink
    # (so `du | less` is AUTO but `foo || less` is a bare pager -> CONFIRM). A single
    # simple command yields one segment (itself); we fall through to base-command
    # classification with the caller's _piped context OR that segment's pipe flag.
    segments = _split_shell(command)
    if len(segments) > 1:
        worst = SafetyTier.AUTO
        for segment, seg_piped in segments:
            tier = classify_command(segment, _piped=_piped or seg_piped)
            if tier == SafetyTier.BLOCKED:
                return SafetyTier.BLOCKED
            if tier == SafetyTier.CONFIRM:
                worst = SafetyTier.CONFIRM
        return worst
    if not segments:
        return SafetyTier.AUTO            # only separators/grouping -> nothing runs
    command, seg_piped = segments[0]      # single command (grouping stripped)
    _piped = _piped or seg_piped

    parts = command.split()
    base_cmd = os.path.basename(parts[0])
    two_word = f"{base_cmd} {parts[1]}" if len(parts) > 1 else ""

    if base_cmd in _BLOCKED_COMMANDS:
        logger.warning("Command blocked: %s", base_cmd)
        return SafetyTier.BLOCKED

    # L2 anti-fabrication (HARD): this system's package manager is pkm. apt /
    # dnf / yum / pacman / zypper / etc. do not exist on InterGenOS, so emitting
    # one is a wrong-system hallucination, not a real action. Block it before
    # the AUTO/CONFIRM tables (so even a read-only `apt list` is caught) and let
    # get_blocked_response redirect the model to the pkm equivalent.
    if base_cmd in WRONG_PKG_MANAGERS:
        logger.warning("Wrong package manager blocked (use pkm): %s", base_cmd)
        return SafetyTier.BLOCKED

    # iproute2-netlink family (ip/ss/bridge/tc/...): the hardened daemon denies
    # AF_NETLINK (F-038), so auto-running one SIGSYS-coredumps the run_command
    # child instead of returning data. Route to BLOCKED before the AUTO/CONFIRM
    # tables so get_blocked_response can redirect to /sys/class/net or the user's
    # own terminal — a clear refusal beats a silent crash. (base_cmd catches all
    # subcommand forms, e.g. `ip addr`, `ip route show`, `ss -tlnp`.)
    if base_cmd in _NETLINK_COMMANDS:
        logger.info("Netlink tool unavailable under F-038 (redirect): %s", base_cmd)
        return SafetyTier.BLOCKED

    # Write-form guard for the AUTO stream filters: sort -o/--output and uniq with an
    # output-file operand WRITE a file, so they are CONFIRM, not AUTO — AUTO must mean
    # cannot-mutate-regardless-of-args, not safe-only-while-the-lockdown-invariant
    # holds on every caller. (cut has no write form; the du|sort -rh|head pipeline has
    # no write flag, so it stays AUTO.) Checked before the AUTO table claims them.
    if base_cmd == "sort" and _sort_writes(parts):
        return SafetyTier.CONFIRM
    if base_cmd == "uniq" and _uniq_writes(parts):
        return SafetyTier.CONFIRM
    # find with a mutate/exec primary (-delete/-exec/-execdir/-fprint/-fprintf/-fls)
    # is CONFIRM, not AUTO — same cannot-mutate-regardless-of-args rule. Read-only
    # find stays AUTO.
    if base_cmd == "find" and _find_mutates(parts):
        return SafetyTier.CONFIRM
    # env is an exec wrapper: classify it by its WRAPPED command (a read stays AUTO,
    # a write confirms, a dangerous one is refused), not as a flat AUTO that would
    # launder `env touch x` / `env <unknown>` past the confirm gate. Bare env (no
    # wrapped command) just prints/sets the environment -> AUTO.
    if base_cmd == "env":
        wrapped = _env_wrapped_command(parts)
        return SafetyTier.AUTO if wrapped is None else classify_command(wrapped, _piped=_piped)

    # watch is an exec wrapper like env: classify by its WRAPPED command so
    # `watch 'rm -rf x'` is BLOCKED and `watch free` is AUTO, never a flat pass.
    if base_cmd == "watch":
        wrapped = _watch_wrapped_command(parts)
        return SafetyTier.AUTO if wrapped is None else classify_command(wrapped, _piped=_piped)

    # Shell (or `script`) with a `-c` command-string: classify the command-string
    # itself (worst tier) so the shell token cannot hide a recognition-tier inner
    # and the separator model applies INSIDE the quoted argument. A bare shell /
    # `bash file.sh` returns None and falls through to the CONFIRM default.
    if base_cmd in _CMDSTRING_WRAPPERS:
        cmd_str = _shell_c_argument(parts)
        if cmd_str:
            return classify_command(cmd_str, _piped=_piped)

    # Transparent exec-prefix wrappers (nohup/nice/timeout/xargs/flock/strace/...):
    # classify by the WRAPPED command so a base-command-keyed block (`nohup sudo …`,
    # `timeout 5 mount /x`, `nice ip addr`, `flock /l pkexec …`) reaches its true
    # tier instead of softening to the unknown-command CONFIRM. Bare wrapper -> AUTO
    # (nothing runs). Like env/watch above.
    if base_cmd in _PREFIX_SPECS:
        wrapped = _prefix_wrapped_command(parts)
        return SafetyTier.AUTO if wrapped is None else classify_command(wrapped, _piped=_piped)

    # Interactive-pager guard: a bare pager is a shell-escapable interactive
    # program -> CONFIRM; a piped pager is a data-sink -> AUTO.
    if base_cmd in _PAGER_COMMANDS:
        return SafetyTier.AUTO if _piped else SafetyTier.CONFIRM
    # $PAGER-paginating tools: AUTO only when non-interactive (piped, or an
    # explicit --no-pager/--no-paginate); else the bare paginating form is
    # escapable -> CONFIRM.
    _noninteractive = _piped or "--no-pager" in parts or "--no-paginate" in parts
    if base_cmd in _PAGINATING_SINGLE:
        return SafetyTier.AUTO if _noninteractive else SafetyTier.CONFIRM
    if base_cmd == "git":
        sub = next((p for p in parts[1:] if not p.startswith("-")), None)  # handles `git --no-pager log`
        if sub in _PAGINATING_GIT_SUBCMDS:
            return SafetyTier.AUTO if _noninteractive else SafetyTier.CONFIRM
    if two_word in _PAGINATING_TWO_WORD:
        return SafetyTier.AUTO if _noninteractive else SafetyTier.CONFIRM

    if two_word in _AUTO_COMMANDS_TWO_WORD:
        return SafetyTier.AUTO
    if base_cmd in _AUTO_COMMANDS_SINGLE:
        return SafetyTier.AUTO

    if two_word in _CONFIRM_COMMANDS_TWO_WORD:
        return SafetyTier.CONFIRM
    if base_cmd in _CONFIRM_COMMANDS_SINGLE:
        return SafetyTier.CONFIRM

    # Unknown commands default to CONFIRM (not AUTO — err on the side of caution)
    logger.debug("Unknown command defaults to CONFIRM: %s", base_cmd)
    return SafetyTier.CONFIRM


# Canonical destructive-EXECUTION patterns (anywhere-match), shared by the
# router's pre-LLM decline gate so it cannot drift from the dispatch-time
# blocker above (WC unification — one source of truth, two call sites). The
# authoritative blocker is classify_command/_BLOCKED_PATTERNS; this set lets the
# router decline an obviously-destructive request instantly, in natural language
# ("Run dd if=..."), which classify_command misses because it keys off the base
# token. The block-device family regex is reused verbatim so a coverage fix
# (e.g. adding virtio) closes the hole at BOTH layers at once.
_DESTRUCTIVE_EXEC = (
    re.compile(r"\bdd\s+.*\b(?:if|of)="),                       # dd if=/of=
    re.compile(r"\bof=/dev/"),
    # mkfs in COMMAND form only (mkfs.ext4 / mkfs -t / mkfs /dev/...), so the
    # informational "what does mkfs do?" still reaches the tools — the gate runs
    # on raw NL, where bare \bmkfs\b would over-block. (The authoritative blocker
    # uses \bmkfs\b on the actual command, which is correct there.)
    re.compile(r"\bmkfs(?:\.\w+|\s+-|\s+/dev/)"),
    re.compile(r"\bwipefs\b"),
    re.compile(r"\bshred\s+-"),
    re.compile(                                                  # recursive+force rm
        r"\brm\b"
        r"(?=.*\s(?:-[a-zA-Z]*[rR]|--recursive))"
        r"(?=.*\s(?:-[a-zA-Z]*[fF]|--force))"
    ),
    re.compile(r":\(\)\s*\{"),                                  # fork bomb
    _BLOCK_DEVICE_REDIRECT,                                      # redirect-wipe to a block device
)


def is_destructive_execution(text: str) -> bool:
    """True when text contains an execution-class destructive pattern.

    Anywhere-match over raw text (natural language or a command string). Shared
    canonical check so the router's pre-decline gate stays in lockstep with the
    dispatch-time denylist and cannot drift from it.
    """
    return any(p.search(text) for p in _DESTRUCTIVE_EXEC)


# ── Natural-language destructive-INTENT gate ──────────────────────────────────
#
# is_destructive_execution (above) keys off command TOKENS (dd / mkfs / rm -rf /
# of=/dev/...). A phrasing-level request that names no command — "format my
# disk", "wipe my drive", "erase everything on my hard drive", "delete
# everything in /etc" — carries none of those tokens, so it slips past that gate
# and reaches the 2B, leaving the refusal to MODEL JUDGMENT rather than a
# deterministic barrier. For the face of a security-only OS that is too thin
# (assume superhuman adversaries; when in doubt, deny). This gate is the
# non-model sibling barrier: a destructive VERB applied to a high-stakes OBJECT.
#
# The two lenses are reconciled deliberately. Security-only alignment wants an
# imperative destructive request declined without consulting the model. The face bar
# ("helpful, not stubborn") wants a genuine QUESTION answered, not refused. So
# informational/how-to framing is EXCLUDED first — "how do I format a USB?",
# "what does mkfs do?", "can I wipe my disk?" route through to a helpful answer —
# while the IMPERATIVE ("format my disk") fires. This is safe because a question
# is not InterGen executing: actual EXECUTION stays independently guarded by
# classify_command's BLOCKED tier and the destructive-policy never-list at the
# dispatch chokepoint. Over-blocking an imperative is the acceptable (safe-side)
# error; over-blocking a question would make him stubborn, so questions pass.
#
# POSTURE — this is a SECOND barrier (defense-in-depth), NOT total coverage. A NL
# denylist has an evadable tail by nature: verb synonyms, deliberate typos
# ("wpe my drive"), an object named in a PRIOR turn (this gate is single-turn),
# or a pronoun reference. It sits in front of the model's own refusal AND the
# dispatch-time classify_command BLOCKED tier + destructive-policy never-list,
# which are the hard guarantees on EXECUTION. This gate's job is to deny obvious
# NL destructive intent deterministically so the refusal does not rest on model
# judgment — not to be a complete classifier. (adversarial review, item 1.)

# A destructive verb/phrase. delete/remove/clear are common verbs, so they only
# trip the gate when paired with a high-stakes OBJECT below (bare "delete
# foo.txt" has no high-stakes object → not flagged → normal CONFIRM-tier path).
_DESTRUCTIVE_INTENT_VERB = re.compile(
    r"\b(?:format|reformat|wipe(?:\s+out)?|erase|nuke|obliterate|annihilate|"
    r"destroy|scrub|shred|overwrite|flatten|trash|blank|purge|zero\s+out|"
    r"get\s+rid\s+of|factory[\s-]*reset|blow\s+away|delete|remove|clear)\b"
)

# A high-stakes target — a whole disk/volume/system or a wholesale "everything".
# Deliberately EXCLUDES a bare "file"/"files" so an ordinary single-file delete
# stays on the normal CONFIRM-tier path; only "all (my) files"/"everything" and
# disk/volume/system/protected-path objects qualify.
_DESTRUCTIVE_INTENT_OBJECT = re.compile(
    r"\b(?:disks?|drives?|hard\s+(?:disk|drive)s?|hdd|ssd|nvme|"
    r"partitions?|file\s*systems?|volumes?|"
    r"everything|all\s+(?:my\s+|the\s+)?(?:files|data|stuff)|"
    r"it\s+all|the\s+whole\s+(?:thing|lot|shebang|drive|disk)|the\s+lot|"
    r"(?:my|the|whole|entire)\s+(?:system|machine|computer|laptop|pc|os|"
    r"install|installation)|"
    r"home\s+(?:directory|dir|folder)|"
    r"root\s+(?:directory|dir|partition|filesystem|fs))\b"
    r"|/(?:etc|boot|usr|var|home|dev|root|bin|lib|sys|opt)\b"   # protected paths
    r"|(?<!\S)/(?!\S)"                                          # bare "/" (root)
)

# Informational / how-to / question framing — checked FIRST and short-circuits to
# False so a genuine question is never hijacked into a refusal. Bounded leading
# filler (up to 3 tokens) so "so how do I…", "hey can I…", "ok, what happens if…"
# are still recognized as questions, while a marker buried AFTER an imperative
# ("format my disk and tell me when done") does NOT match and the gate still fires.
_INFORMATIONAL_LEADIN = re.compile(
    r"^\s*(?:\S+\s+){0,3}?"
    r"(?:how\s+(?:do|to|can|could|would|should|does|did|long|much|many)"
    r"|what(?:'s|\s+is|\s+are|\s+does|\s+do|\s+happens|\s+would)"
    r"|why\s+(?:do|does|would|is|are)"
    r"|when\s+(?:do|does|should|would)"
    r"|where\s+(?:do|is|are|can)"
    r"|is\s+it\s+(?:safe|possible|ok|okay|advisable|a\s+good)"
    r"|is\s+there|are\s+there"
    r"|should\s+i|can\s+i|could\s+i|do\s+i|would\s+i|may\s+i"
    r"|can\s+you\s+(?:explain|tell|describe|show|walk)"
    r"|explain|describe|tell\s+me|show\s+me\s+how|walk\s+me\s+through"
    r"|i'?m\s+(?:curious|wondering)|i\s+wonder"
    r"|difference\s+between|what\s+happens\s+if)"
    r"\b"
)

# An explicit ACTION DIRECTIVE — "just do it" / "go ahead" / "do it now" at the
# END of the input — means the request is a COMMAND despite a how-to prefix, so it
# RE-ENABLES the gate (anti prefix-bypass: "how do I wipe the drive — just do it").
# It is END-ANCHORED and limited to unambiguous do-it phrases on purpose: a SOFT
# directive mid-sentence ("should I wipe my disk before I go ahead and reinstall
# the OS", "what should I actually do to wipe my disk") is ordinary narrative
# inside a genuine QUESTION and must NOT re-capture it — so the override fires only
# when the do-it phrase sits at end-of-input. (adversarial review, item 1 — the
# security-critical bypass plus the finding-1 over-decline it introduced.)
_ACTION_DIRECTIVE = re.compile(
    r"(?:just\s+do\s+it|do\s+it(?:\s+(?:now|already|anyway|for\s+me))?"
    r"|go\s+ahead|do\s+that\s+now|make\s+it\s+(?:so|happen))"
    r"(?:\s+(?:please|now|already|anyway|thanks?))?\s*[-—.!,]*\s*$"
)

# Removable USER media — a thumb drive, external disk, SD card. Reformatting one
# is a normal thing a user OWNS and wants, so a destructive imperative scoped to
# removable media is routed to the helpful/confirm path, NOT a stubborn hard
# decline (the helpfulness FACE bar; execution is still guarded at dispatch). The
# phrase includes the object noun so stripping it removes the high-stakes object
# word — is_destructive_intent re-checks the stripped text, so a COMPOUND request
# ("wipe my disk and my usb drive") still fires on the bare system object.
# (adversarial review, item 1 — the over-decline finding.)
# Known residual (accepted denylist tail): a WHOLESALE object scoped to removable
# media ("erase everything on my usb stick") still fires — the strip rescues only
# when the removable noun IS the high-stakes object; the dispatch layer remains the
# hard guarantee, so this is left rather than chased.
_REMOVABLE_MEDIA = re.compile(
    r"\b(?:usb|external|removable|portable|thumb|flash|pen)\s+"
    r"(?:hard\s+)?(?:drives?|disks?|sticks?|hdd|ssd|storage)\b"
    r"|\b(?:micro\s*)?sd\s*cards?\b"
    r"|\bpen\s*drives?\b"
    r"|\bthumb\s*drives?\b"
    r"|\busb\s+sticks?\b"
    r"|\bmemory\s+(?:stick|card)s?\b"
    r"|\bflash\s+(?:drive|disk)s?\b"
)


def is_destructive_intent(text: str) -> bool:
    """True when raw NL expresses an IMPERATIVE destructive intent on a
    high-stakes target — the natural-language sibling of is_destructive_execution.

    Predicate: a destructive VERB applied to a high-stakes OBJECT. Informational/
    how-to framing is excluded so a genuine question routes to a helpful answer —
    UNLESS an explicit action directive ("just do it") rides on it, which marks a
    real command wrapped in a question prefix (the prefix-bypass). See the block
    comment above for the lens reconciliation and the defense-in-depth posture.
    """
    t = text.strip().lower()
    if not t:
        return False
    has_intent = bool(
        _DESTRUCTIVE_INTENT_VERB.search(t)
        and _DESTRUCTIVE_INTENT_OBJECT.search(t)
    )
    if not has_intent:
        return False
    # Removable USER media → helpful/confirm path, not a stubborn hard decline.
    # Strip removable noun-phrases and re-check: if NO high-stakes object remains,
    # the intent was scoped to removable media (a normal reformat) → don't fire.
    # A compound request keeps its bare system object after the strip → still fires.
    if not _DESTRUCTIVE_INTENT_OBJECT.search(_REMOVABLE_MEDIA.sub(" ", t)):
        return False
    # An explicit do-it directive overrides the informational exclusion — a real
    # command wrapped in a question prefix still fires (anti prefix-bypass).
    if _ACTION_DIRECTIVE.search(t):
        return True
    if _INFORMATIONAL_LEADIN.search(t):
        return False
    return True


