# A code-owned screen over the model's freeform DRAFT, before delivery. It catches
# ONE class — an unfounded first-person execution CLAIM on a turn where NOTHING was
# dispatched (the fab_stale_offer signature: "I've kicked it off in the background"
# on a locked freeform turn). It re-grounds the model; it does NOT cage general
# language (anti-lobotomy): the marker set is first-person completed/in-progress
# actions only, and every match is negation-guarded so the model's own HONEST
# denials ("I didn't run anything", "nothing has been started") never trip it.
#
# The regex encodes the subject INLINE so a negator sitting between the pronoun and
# the verb ("I did NOT run", "has NOT been started") structurally cannot match, and
# conditionals/instructions ("I'd run", "I would run", "to run it, use…") are not
# claims and also do not match. Aligned with the grader's Gate-A fabrication class
# (_affirmative_success_claim) — the "successfully" marker reuses the same
# negation-window guard so a negated "did not run successfully" stays honest.
_EXEC_CLAIM_RE = re.compile(
    r"\b(?:"
    # first-person completed action (perfect / simple-past). "I('ve/have/already/
    # just/now) <verb-past>". A negator between pronoun and verb ("I did NOT run")
    # cannot match by construction; a FUTURE "I'll run" / "I would run" is not a
    # claim and does not match ("'ll"/"would" are not the required \s+<verb>).
    r"i(?:['’]ve| have| already)?\s+(?:just\s+)?(?:now\s+)?"
    r"(?:ran|run|executed|started|launched|triggered|initiated|installed|"
    r"updated|upgraded|synced|began|begun|"
    r"kicked[\s-]+off|kicked\s+(?:it|that|the\s+\w+)\s+off|fired[\s-]+off)\b"
    # first-person IN-PROGRESS action ("I'm/I am (now/currently/already) <gerund>")
    r"|i(?:['’]m| am)\s+(?:now\s+|currently\s+|already\s+)?(?:in\s+the\s+"
    r"process\s+of\s+)?(?:running|executing|starting|installing|updating|"
    r"upgrading|launching|initiating|syncing|triggering|beginning|"
    r"kicking[\s-]+off|firing[\s-]+off)\b"
    # ── VERIFICATION claims (decided 2026-07-24, the fabricated-verification
    # class): "I checked lsblk and df -h" sailed through this screen because the
    # marker set was execution/creation-shaped only — no verification verbs. A
    # first-person past-tense claim of having CHECKED/VERIFIED system state is
    # an action claim like any other (action-claim ⇒ tool span, the ratified
    # invariant; live-reproduced on the dogfood 35B at tools=0 with confabulated
    # disk topology). OBJECT-ANCHORED by design: the verb must be followed
    # within the sentence by a system-state noun or a command name, so honest
    # documentation references ("I checked the wiki") and abstract hedges stay
    # unflagged — the citation surface owns those. Negation is excluded by the
    # same inline-subject construction as the alternations above ("I couldn't
    # check" / "I have not verified" structurally cannot match).
    r"|i(?:['’]ve| have| already| just)?\s+(?:just\s+|now\s+|double[\s-]?|re[\s-]?)?"
    r"(?:checked|verified|confirmed|inspected|examined|queried|measured|"
    r"reviewed|looked\s+at)\b"
    r"[^.?!]{0,60}?\b(?:(?:lsblk|df|du|free|lscpu|lspci|lsusb|lpstat|ps|top|"
    r"ip|mount|uname|smartctl|sensors|systemctl|journalctl|nmcli|iwconfig)\b"
    r"|(?:disk|drive|partition|filesystem|storage|volume|memory|ram|swap|cpu|"
    r"process|service|unit|daemon|log|journal|network|interface|connection|"
    r"printer|queue|device|package|update)(?:es|s)?\b"
    r"|(?:hardware|kernel|boot|system\s+state|machine|the\s+output)\b)"
    # premature-action ADMISSION — on a zero-dispatch turn this is always a
    # fabricated account of having acted ("I jumped the gun on executing …").
    r"|jumped\s+the\s+gun\b|got\s+ahead\s+of\s+myself\b"
    # passive "has/have been <verb>" — the action is asserted to have happened
    r"|(?:has|have)\s+been\s+(?:executed|started|run|launched|kicked[\s-]+off|"
    r"initiated|installed|updated|upgraded|synced)\b"
    # standalone claim that a job is now running/underway (in the background)
    r"|(?:is|are)\s+(?:now\s+)?(?:running\s+in\s+the\s+background|underway|"
    r"in\s+progress)\b"
    # ── M7 leg 1 (CRITICAL, the fab_completion class) — first-person PAST-TENSE
    # COMPLETION claims that assert a FILESYSTEM / permission outcome ("I've saved
    # it to ~/hello.sh", "I've placed it in your home directory", "I made it
    # executable"). The pre-M7 markers caught present/future/in-progress action
    # language but MISSED a completed write ("I've made/placed/saved …"), so a
    # fabricated "here is the script saved directly to ~/hello.sh" passed clean on a
    # zero-dispatch turn (2026-07-08 finding 1; PI-Z23 sibling). LOCATION/permission-
    # anchored so presenting code INLINE ("I wrote a short script:") is NOT a claim —
    # only a claim that the artifact reached the filesystem is flagged.
    r"|i(?:['’]ve| have| already| just)?\s+(?:just\s+|now\s+)?"
    r"(?:saved|placed|put|created|wrote|written|generated|dropped|stored)\b"
    r"[^.?!]{0,40}?\b(?:to|in|into|at|under|on)\b[^.?!]{0,30}?"
    r"(?:~|/|home\s+director|desktop|documents?|downloads?|disk|"
    r"the\s+file|a\s+file|your\s+\w+\s+(?:director|folder)|path)"
    # first-person completion naming a FILE with an extension ("I've created
    # report.md", "I've saved notes.txt to your home folder"). The filename itself is
    # the filesystem claim (no location anchor needed) — and the '.' in the name would
    # otherwise break the location-anchored alt above ([^.?!] cannot cross it).
    r"|i(?:['’]ve| have| already| just)?\s+(?:just\s+|now\s+)?"
    r"(?:saved|placed|put|created|wrote|written|generated|dropped|stored)\b"
    r"\s+(?:it\s+)?(?:to\s+|in\s+|into\s+|as\s+)?['\"]?[\w\-]+\.[a-z0-9]{1,6}\b"
    # "made it executable" / "made the script runnable" — a permission completion
    r"|i(?:['’]ve| have| already| just)?\s+(?:just\s+|now\s+)?made\b"
    r"[^.?!]{0,30}\b(?:executable|runnable)\b"
    # presentational completion — "here is the script saved (directly) to ~/x",
    # "here's the file created at …": a completed write presented in the third person.
    r"|here(?:['’]s|\s+is|\s+are)\b[^.?!]{0,40}\b"
    r"(?:saved|created|written|placed|generated)\b[^.?!]{0,20}?\b(?:to|in|at|under)\b"
    # re-claim of a prior (fabricated) file action — "the script I saved",
    # "the file I created", "the program I wrote".
    r"|the\s+(?:script|file|program|command|note|document|config)\s+i\s+"
    r"(?:saved|created|wrote|made|placed|generated|put|stored)\b"
    r")",
    re.IGNORECASE)
# Negators for the "successfully" marker (mirrors the grader's window guard): a
# NEGATED "successfully" is an honest failure report, not a success claim.
_EXEC_CLAIM_NEGATORS = re.compile(
    r"\b(not|never|unable|fail|failed|fails|cannot|can't|could\s?n['’]?t|"
    r"did\s?n['’]?t|does\s?n['’]?t|do\s?n['’]?t|was\s?n['’]?t|"
    r"were\s?n['’]?t|is\s?n['’]?t|are\s?n['’]?t|no|nothing|none|neither|"
    r"nor|without)\b")


# ── BARE PRESENT-PROGRESSIVE claim (the anchor-0001 shape) ──
# The pronoun is dropped entirely: "Running `pkm install htop` now",
# "Installing htop now." Measured before landing: the straightforward version of
# this rule scored 50% false positives on its own hit set, because an honest
# denial-plus-offer ("I didn't kick off an update… start updating the system
# now?") is built from the same words. The words are therefore not the whole
# rule — the match must OPEN its clause (a gerund mid-sentence is a description,
# "running that would refresh the index"), and the clause must be neither
# negated nor interrogative.
_BARE_PROGRESSIVE_RE = re.compile(
    r"\b(?:running|executing|installing|updating|upgrading|starting|launching|"
    r"initiating|syncing|triggering|removing|uninstalling)\b"
    r"[^.?!\n]{0,60}?\b(?:now|in\s+the\s+background)\b",
    re.IGNORECASE)

# A claim lives in a clause. These end one.
#
# Sentence punctuation is the obvious boundary, but it is not the only one: a
# comma followed by a coordinating conjunction starts a NEW assertion inside the
# same sentence, and that is the most natural way to write the fabrication this
# screen exists to catch — "I could not find it in the cache, so I installed it
# from source." Measured on this module before the boundary was added: with only
# `[.!?\n]`, the leading denial sat in the same clause as the later claim and
# amnestied it, so a draft claiming an action on a turn that dispatched nothing
# came back clean. The negation still carries across the comma whenever it is
# restated in the second clause ("…, and I am not installing anything now"),
# which is what keeps the honest denial-plus-continuation passing.
_CLAUSE_END = re.compile(r"[.!?\n]|,\s+(?:so|and|then|but|yet)\b")
# Offer openers — the clause proposes an action instead of asserting one.
_OFFER_OPENER = re.compile(
    r"^\s*(?:shall\s+i|should\s+i|can\s+i|may\s+i|do\s+you\s+want|"
    r"would\s+you\s+like|want\s+me\s+to|would\s+you\s+want|"
    r"if\s+you(?:['’]d| would)?\s+like|let\s+me\s+know)\b")


def _clause_bounds(low: str, at: int) -> tuple[int, int]:
    """The clause containing offset `at`, as (start, end)."""
    start = 0
    for m in _CLAUSE_END.finditer(low, 0, at):
        start = m.end()
    end_m = _CLAUSE_END.search(low, at)
    return start, (end_m.end() if end_m else len(low))


def _claim_is_live(low: str, start: int, end: int, match_start: int) -> bool:
    """Is this clause actually ASSERTING the action?

    Two shapes are not claims, and both were measured on real replies:
      * NEGATED — a negator precedes the claim inside its own clause ("nothing
        has been started", "I didn't kick off an update"). The module's contract
        has always said honest denials never trip the screen; scoping the guard
        to the clause is what makes that true for every alternation rather than
        only the ones whose subject is spelled inline.
      * INTERROGATIVE / OFFERED — the clause is a question or proposes the
        action ("start updating the system now?", "would you like me to…"). An
        offer asserts that nothing has happened, which is the opposite of a
        fabrication.
    """
    clause = low[start:end]
    if clause.rstrip().endswith("?"):
        return False
    if _OFFER_OPENER.search(clause):
        return False
    before = low[start:match_start]
    if _EXEC_CLAIM_NEGATORS.search(before):
        return False
    return True


def _execution_claim_marker(text: str) -> str | None:
    """Return the matched execution-claim phrase, or None.

    Every match is clause-guarded: a claim inside a negated or interrogative
    clause is not a claim. An AFFIRMATIVE "successfully" also fires,
    negation-window-guarded.
    """
    low = text.lower()
    for m in _EXEC_CLAIM_RE.finditer(low):
        start, end = _clause_bounds(low, m.start())
        if _claim_is_live(low, start, end, m.start()):
            return m.group(0).strip()
    for m in _BARE_PROGRESSIVE_RE.finditer(low):
        start, end = _clause_bounds(low, m.start())
        # Clause-INITIAL only: "Installing htop now" asserts; "…by installing
        # htop now" describes.
        if low[start:m.start()].strip(" \t-*•"):
            continue
        if _claim_is_live(low, start, end, m.start()):
            return m.group(0).strip()
    # "successfully" — affirmative only (a negated one is honest failure reporting)
    for occ in re.finditer(r"successfully", low):
        if low[max(0, occ.start() - 2):occ.start()] == "un":  # unsuccessfully
            continue
        if _EXEC_CLAIM_NEGATORS.search(low[max(0, occ.start() - 40):occ.start()]):
            continue
        return "successfully"
    return None


def screen_execution_claim(draft: str, dispatched: bool) -> tuple[str, str | None]:
    """M3(ii): screen a model draft for an unfounded execution claim.

    Returns (verdict, marker): ("clean", None) when the turn actually dispatched a
    tool OR the draft makes no execution claim; ("violation", <marker>) when the
    draft claims a first-person action AND nothing was dispatched this turn. The
    caller regenerates ONCE with a corrective note, then falls back to an honest
    line — it never ships a fabrication."""
    if dispatched:
        return ("clean", None)
    marker = _execution_claim_marker(draft or "")
    return ("violation", marker) if marker else ("clean", None)


def honest_action_fallback() -> str:
    """Deterministic, non-fabricating reply for the (rare) case where the model
    still claims a phantom action after one corrective regeneration. Honesty over
    helpfulness — the security-first bar: never ship a fabricated action claim."""
    return ("I want to be accurate here: I have not run, started, or executed "
            "anything this turn — nothing was dispatched. If you'd like me to do "
            "something, tell me and I'll ask you to confirm first.")


# ── M7 leg 2: model-authored OFFER on a toolless turn — the root enabler of leg 1 ──
#
# On a toolless turn the model's own TEXT can stage an offer ("Say yes and I'll take
# care of pkm sync && pkm upgrade", "Want me to write it for you and save it
# directly?") that NO code-owned machinery tracks. A later affirmative then binds to
# nothing code-side, and the model narrates a completion it never performed (leg 1;
# 2026-07-08 finding 1, PI-Z23 (a)). The staged-offer machinery (M8-4/M8-1) is
# code-owned precisely so the offer surface is auditable — a model-authored offer
# must not masquerade as that gate. The screen re-grounds the model; the code-owned
# offer line stays the ONLY offer surface.
#
# High-precision by construction: an OFFER FRAME (say-yes-and-I'll / want-me-to /
# shall-I / I'll-… -for-you) AND an ACTION verb must BOTH be present, so an offer to
# EXPLAIN or CLARIFY ("want me to explain how that works?") is never flagged — only
# an offer to PERFORM a system action the toolless model cannot back.
_MODEL_OFFER_FRAME_RE = re.compile(
    r"\bsay\s+(?:yes|the\s+word)\s+and\s+i(?:['’]ll| will| can)\b"
    r"|(?:just\s+)?let\s+me\s+know\s+(?:if\s+you(?:['’]d| would)?\s+(?:like|want)|"
    r"and\s+i(?:['’]ll| will))\b"
    r"|\bwant\s+me\s+to\b"
    r"|\b(?:would\s+you\s+like|shall)\s+(?:me|i)\b"
    r"|\bi(?:['’]ll| will| can|['’]d\s+be\s+happy\s+to)\s+(?:go\s+ahead\s+and\s+)?"
    r"[^.?!]{0,30}?\bfor\s+you\b",
    re.IGNORECASE)
_MODEL_OFFER_ACTION_RE = re.compile(
    r"\b(?:run|execute|install|reinstall|uninstall|update|upgrade|sync|write|save|"
    r"create|make\s+(?:it|that|the)|set\s+up|configure|delete|remove|download|"
    r"fetch|start|stop|restart|enable|disable|launch|generate|build|kick\s+off|"
    r"take\s+care\s+of|handle\s+(?:it|that)|do\s+(?:it|that|this))\b",
    re.IGNORECASE)


def screen_model_text_offer(draft: str, *, dispatched: bool,
                            code_offer_staged: bool) -> tuple[str, str | None]:
    """M7 leg 2: screen a model DRAFT for a self-authored offer to PERFORM an action
    on a toolless turn that no code-owned offer backs. Returns (verdict, marker):
    ("clean", None) when the turn dispatched, OR a code-owned offer is staged this
    turn (the offer is legitimate — its confirmation is code-tracked), OR the draft
    poses no self-offer; ("violation", <frame>) when the draft offers to act and
    nothing code-side can honor it. The caller regenerates ONCE re-grounded, else
    serves the honest no-self-offer fallback."""
    if dispatched or code_offer_staged:
        return ("clean", None)
    text = draft or ""
    fm = _MODEL_OFFER_FRAME_RE.search(text)
    if not fm or not _MODEL_OFFER_ACTION_RE.search(text):
        return ("clean", None)
    return ("violation", fm.group(0).strip())


def model_offer_correction_note() -> str:
    """Corrective note for regeneration: the model has no tools this turn, so it must
    not pose a bindable self-offer. Honest INPUT, never scripted output."""
    return ("You have NO tools available this turn — you cannot run, install, update, "
            "write, save, or otherwise perform any action yourself. Do NOT offer to "
            "do it and invite the user to 'say yes' — there is no mechanism behind "
            "such an offer, so a later 'yes' would only make you claim you did "
            "something you did not. Instead, either explain how the USER can do it "
            "themselves, or say plainly that you can't do it directly. Rewrite your "
            "answer accordingly.")


def honest_no_selfoffer_fallback() -> str:
    """Deterministic non-fabricating reply if the model still poses a self-offer
    after one corrective regeneration. Honesty over helpfulness."""
    return ("To be straight about what I can do here: I can't run, install, or save "
            "anything on my own this turn. If you'd like me to do something, tell me "
            "and I'll ask you to confirm before anything happens — I won't promise to "
            "do it and then act as if it were done.")


# ── M8-2 RESULT DELIVERY INVARIANT: a dispatched tool's result ALWAYS reaches ──
# the delivered answer, or the turn fails loud. The dispatched-but-discarded class
# (ledger sf_dispatch_run_command-20) is a SUCCEEDING read whose value never enters
# the delivered text — either an empty delivery (a streamed synthesis that yielded
# no token while the tool executed) or a DEFLECTION ("I don't have current data")
# rendered ALONGSIDE a successful result. Both are silent today; this makes them a
# NAMED, LOUD defect event so the FIRE->OBSERVE loop can see them per turn.
#
# High-precision by construction: only a result that actually EXECUTED, SUCCEEDED,
# was NOT blocked, and carries deliverable content is checked — a refusal/deny/block
# legitimately delivers a deterministic template and is never flagged. A paraphrased
# (non-verbatim) synthesis is NOT flagged (delivered text is non-empty + carries no
# deflection marker), so an honest summary never false-positives.
_DELIVERY_DEFLECTION_RE = re.compile(
    r"i\s+don'?t\s+have\s+(?:current\s+data|access|(?:the\s+)?(?:current|live|real[- ]?time)"
    r"\s+\w+)|i\s+can'?t\s+(?:verify|access|determine)\b|"
    r"without\s+(?:running|a\s+tool|current\s+data)\b|"
    r"i\s+have\s+not\s+(?:run|started|executed)\b",
    re.IGNORECASE)
# M7 leg 4: a THIRD dispatched-but-discarded shape the deflection regex missed — a
# successful dispatch whose delivered answer TEACHES the user to run the command
# ("here's how you'd check: `lpstat -p`") instead of REPORTING the result the
# dispatch already produced (2026-07-08 finding 3; PI-Z23 (e), the promise-shaped
# non-answer). The text is non-empty and non-deflecting, so it escaped M8-2; this
# closes the seam so it, too, is a NAMED, LOUD defect. High-precision: the markers
# address the USER with a run-it-yourself instruction ("here's how you'd", "you can
# run", "run the following") — a genuine result REPORT never instructs the user to
# run the command that already ran.
_DELIVERY_EXPLAIN_INSTEAD_RE = re.compile(
    r"here(?:['’]s| is)\s+how\s+(?:you(?:['’]d| would| can)?|to)\b"
    r"|you(?:['’]d| would)?\s+(?:can|could|should)?\s*(?:run|use|type)\s+"
    r"(?:the\s+)?(?:following\s+)?(?:command|`)"
    r"|to\s+(?:check|see|list|find\s+out|view|get)\b[^.?!]{0,40}?\b(?:run|use|type)\b"
    r"|run\s+the\s+following\b|try\s+running\b|you\s+can\s+use\s+the\s+command\b",
    re.IGNORECASE)


# ── Is the result ACTUALLY in the answer? (the precision half) ────────────────
# Measured on the whole-battery run at dev 601b2f790: both M8-2 warnings it
# emitted were about answers that CARRIED the dispatch result. do-for-me-04
# reported "441 active services are running." and then denied having the data;
# do-for-me-06 reported all five search results and then added one "you can use
# the `crontab` command" sentence. The text-shape tests above searched the whole
# answer for a marker and never asked whether the result was also in it, so a
# reported result plus one stray sentence read as a discarded result.
#
# WHY THIS TEST MAY ONLY EXCULPATE, NEVER ACCUSE. The docstring below records why
# token overlap cannot be used to DECLARE a dropped result: the memory and disk
# summarizers answer from an authoritative live source by ratified design and
# share no token with the tool result beside them, so a low-overlap rule would
# fire on correct answers. That argument is one-directional. HIGH overlap is
# still sound evidence that the value reached the answer, and using it only to
# withhold an accusation cannot manufacture a false one — the worst case is the
# pre-existing behaviour for an honest paraphrase, which was never flagged
# anyway.
#
# DELIBERATELY CONSERVATIVE. Whole-token matching only (so "printer" in a result
# is not evidenced by the word "printers" in a run-it-yourself sentence — the M7
# leg-4 fixtures depend on that), a distinctive-token floor of two, and a result
# carrying fewer than two distinctive tokens can never exculpate.
_RESULT_TOKEN_RE = re.compile(r"[A-Za-z]{5,}|\d{2,}")
_EVIDENCE_MIN_TOKENS = 2      # below this the answer is not evidence of anything
_EVIDENCE_MIN_RATIO = 0.25    # ... or a large absolute count, for long outputs
_EVIDENCE_ABS_TOKENS = 6


def _distinctive_tokens(text):
    """Lower-cased words of 5+ letters and numbers of 2+ digits, de-duplicated.

    Short words and single digits are dropped because they recur in ordinary
    prose ("the", "1"), and a match on them would be coincidence rather than
    evidence that a particular tool result reached a particular answer.
    """
    return {m.group(0).lower() for m in _RESULT_TOKEN_RE.finditer(text or "")}


def result_reached_text(result, delivered_text) -> bool:
    """True when the delivered answer demonstrably CARRIES this result's value.

    Used only to withhold a "the result did not reach the answer" finding, never
    to raise one — see the block comment above for why that direction is sound
    in this codebase and the other is not.
    """
    payload = (getattr(result, "content", "") or "") + " " + \
              (getattr(result, "model_summary", "") or "")
    tokens = _distinctive_tokens(payload)
    if len(tokens) < _EVIDENCE_MIN_TOKENS:
        return False
    present = tokens & _distinctive_tokens(delivered_text)
    if len(present) < _EVIDENCE_MIN_TOKENS:
        return False
    return (len(present) >= _EVIDENCE_ABS_TOKENS
            or len(present) / len(tokens) >= _EVIDENCE_MIN_RATIO)


# Which findings can be repaired by stating the result, and which may not be.
# "substituted" is absent on purpose: the linkage signal cannot separate a real
# substitution from a summarizer answering off an authoritative live source, so
# rewriting that class would overwrite correct answers. "contradicted_despite_
# result" is absent because the value is already in the answer — there is
# nothing to carry in, and the defect there is the denial beside it.
_REPAIRABLE_REASONS = frozenset({
    "empty_delivery", "deflection_despite_result", "explain_instead_of_result"})


def carry_result_into_answer(delivered_text, result, reason):
    """The answer a user should have received, or None to leave it alone.

    A successful dispatch's value is never discarded: when the model returned
    nothing, denied having the data, or taught the command instead of reporting
    it, the tool's own output IS the answer and is stated as the tool produced
    it.

    A denial is REPLACED rather than annotated — leaving "I don't have current
    data" above the data would manufacture exactly the self-contradiction that
    do-for-me-04 was flagged for. A teaching answer KEEPS its instructions below
    the result, because they are useful and are not a false statement about what
    the system knows.
    """
    if reason not in _REPAIRABLE_REASONS:
        return None
    payload = (getattr(result, "model_summary", "")
               or getattr(result, "content", "") or "").strip()
    if not payload:
        return None
    text = (delivered_text or "").strip()
    if reason == "explain_instead_of_result" and text:
        return f"{payload}\n\n{text}"
    return payload


def find_unconsumed_dispatches(delivered_text, tool_results, linkage=None):
    """M8-2 (+ M7 leg 4): return [(result, reason)] for each executed+successful
    dispatch whose value did NOT reach the delivered answer. Empty list == invariant
    holds.

    reason is "empty_delivery" (successful dispatch but a blank answer),
    "deflection_despite_result" (the answer deflects/denies data while a successful
    dispatch carrying content is in hand), "explain_instead_of_result" (M7 leg 4:
    the answer teaches the user to run the command instead of reporting its result),
    "contradicted_despite_result" (the answer STATES the result and then denies
    having the data — the value reached the answer, so this one is not a drop and
    is never repaired by restating it), or "substituted" (below). All are the dispatched-but-discarded class; the caller
    emits a named glass defect + a loud log line per problem.

    SUBSTITUTED (the fourth reason). The first three are TEXT SHAPES: they catch a
    reply that is blank, that denies having data, or that teaches instead of
    reporting. A reply that confidently states something ELSE is none of those, and
    was structurally invisible — a package dispatch rendered through a disk
    summarizer delivered "Disk usage is available." and tripped nothing, on any of
    the three delivery surfaces.

    It is caught here on the LINKAGE SIGNAL (``linkage``, an AnswerLinkage saying
    what the text was actually composed from), never on text overlap between the
    answer and the tool output. Overlap is unsound in this codebase: the memory and
    disk summarizers answer from an authoritative live source by ratified design and
    share no token with the tool result beside them, so an overlap test would fire
    on correct answers and teach everyone to ignore it.

    A successful dispatch is SUBSTITUTED when the linkage says the delivered text
    came from something else — cached state, a code-owned string, free model text,
    or a DIFFERENT dispatch than the one in hand. ``linkage=None`` means the
    composing site declared nothing; that is not evidence of substitution, so no
    reason is raised (the caller records the absent signal separately, so an
    uninstrumented path stays visible instead of silently exempt).
    """
    problems: list[tuple[object, str]] = []
    text = (delivered_text or "").strip()
    for r in (tool_results or []):
        if not (getattr(r, "executed", False)
                and getattr(r, "success", False)
                and not getattr(r, "blocked", False)):
            continue
        if not (getattr(r, "content", "") or getattr(r, "model_summary", "")):
            continue
        # Whether the value is in the answer decides which finding this is — a
        # marker beside a result that IS reported is not a discarded result.
        evidenced = result_reached_text(r, text)
        if not text:
            problems.append((r, "empty_delivery"))
        elif _DELIVERY_DEFLECTION_RE.search(text):
            # Evidenced: the answer states the result AND denies having it (the
            # do-for-me-04 shape) — a real defect, but a contradiction, not a
            # drop, and no repair can carry in what is already there.
            problems.append((r, "contradicted_despite_result" if evidenced
                             else "deflection_despite_result"))
        elif _DELIVERY_EXPLAIN_INSTEAD_RE.search(text):
            # Evidenced: the result is reported and the answer then teaches the
            # command as well (the do-for-me-06 shape). Nothing was discarded,
            # so nothing is flagged; the substitution test below is moot for the
            # same reason.
            if not evidenced:
                problems.append((r, "explain_instead_of_result"))
        elif _is_substituted(r, linkage):
            problems.append((r, "substituted"))
    return problems


def _is_substituted(result, linkage) -> bool:
    """True when ``linkage`` says the delivered text was NOT composed from
    ``result`` — the dispatch ran and something else was served in its place.

    Undeclared linkage returns False: absence of a signal is not evidence. A
    linkage that names a dispatch matches when it names THIS one; a call_id is
    compared when both carry one, so a route that records the tool but not the id
    still matches on the tool rather than raising a false substitution.
    """
    if linkage is None:
        return False
    if getattr(linkage, "kind", "") != "dispatch":
        return True
    call_id = getattr(linkage, "call_id", "") or ""
    r_call_id = getattr(result, "call_id", "") or ""
    if call_id and r_call_id:
        return call_id != r_call_id
    tool = getattr(linkage, "tool", "") or ""
    name = getattr(result, "name", "") or ""
    return bool(tool and name and tool != name)


# ── M4 capability-claim gate: checkable claims about OUR system are verified ──
# against ground truth before delivery (PI-Z23 b — the `pkm add` invention class).
#
# A CLAIM gate, not a topic gate (anti-lobotomy): the model keeps the WHOLE
# conversational surface; only a claim that INVOKES a pkm subcommand which does not
# exist is caught and re-grounded against the real parser surface. The valid set is
# DERIVED from data/capability-surface.json (introspected pkm argparse + intergen
# ToolRegistry) — no hand-kept copy to drift out of sync with the real parser
# (the drift finding).
#
# GROUND TRUTH ABSENT = FAIL LOUD, never silent (fail-loud rule, 2026-07-07; the
# installed-box no-data observation proved the failure mode is real). A missing /
# unreadable surface does NOT let the gate wave every draft through green — a silent
# no-op gate is a stub-shaped lie. Instead screen_capability_claim returns the
# distinct "unavailable" verdict so the router (a) emits a decision/capability_screen
# WARN row EVERY turn (the degradation is never silent) and (b) will not deliver an
# UNVERIFIABLE `pkm <sub>` claim as if verified — it serves the honest-under-
# uncertainty fallback. Dispatch stays LOCKED regardless; this is the grounding layer.
_CAP_SURFACE_PATH = Path(__file__).with_name("data") / "capability-surface.json"


@functools.lru_cache(maxsize=1)
def _pkm_surface() -> tuple[frozenset[str], tuple[str, ...]]:
    """(valid_names, primary_subcommands_sorted) from the surface artifact.
    valid_names includes aliases (for matching); primary is the subcommand keys
    (for the corrective note). Empty on a missing/broken artifact."""
    try:
        surf = json.loads(_CAP_SURFACE_PATH.read_text())
    except (OSError, ValueError) as e:
        # Ruling 2: ground truth absent is a LOUD degradation, not a silent no-op.
        # lru_cache means this journal breadcrumb fires once per process; the
        # per-turn glass WARN (router capability_screen "unavailable") is the SSoT.
        logger.warning("capability-surface.json unreadable (%s) — capability gate "
                       "DEGRADED: pkm claims cannot be verified until it ships at "
                       "%s", e, _CAP_SURFACE_PATH)
        return frozenset(), ()
    subs = surf.get("pkm", {}).get("subcommands", {})
    names: set[str] = set()
    for name, spec in subs.items():
        names.add(name)
        names.update(spec.get("aliases", []))
    if not names:
        logger.warning("capability-surface.json at %s has no pkm subcommands — "
                       "capability gate DEGRADED (unverifiable)", _CAP_SURFACE_PATH)
    return frozenset(names), tuple(sorted(subs.keys()))


# A `pkm <subcommand>` INVOCATION in the draft — high-precision so prose ("the pkm
# package manager") and package-name positions never match: only a backtick code
# span (`pkm add …`) or an imperative lead-in (run/use/type/try pkm add …). The
# subcommand is the first non-flag token after `pkm`; leading global flags are
# skipped.
_PKM_INVOKE_RE = re.compile(
    r"(?:`\s*|(?:\b(?:run|use|type|enter|execute|try|via|invoke|just\s+run|"
    r"command\s+is|command:)\s+))"
    r"pkm\s+(?:-{1,2}[a-z][\w-]*\s+)*([a-z][a-z0-9-]*)",
    re.IGNORECASE)
# Honest correction / negation guard: the model naming an invalid subcommand while
# DENYING it ("there is no `pkm add`", "not `pkm add` — use `pkm install`") is
# correct behavior and must never trip the gate (anti-lobotomy).
_CAP_NEGATORS = re.compile(
    r"\b(no|not|never|isn['’]t|aren['’]t|instead\s+of|rather\s+than|unlike|"
    r"avoid|there\s+is\s+no|there['’]s\s+no|no\s+such|don['’]t|doesn['’]t|"
    r"wouldn['’]t|can['’]t|cannot)\b", re.IGNORECASE)


def _find_pkm_invocation(text: str) -> tuple[str, str] | None:
    """First non-negated `pkm <subcommand>` invocation in text as (sub, "pkm sub"),
    or None. Validity is NOT judged here — the caller compares against the surface
    (fabrication) or, when the surface is missing, treats any hit as unverifiable.
    A negated/correcting window ("there is no `pkm add`") is skipped (anti-lobotomy)."""
    for m in _PKM_INVOKE_RE.finditer(text):
        window = text[max(0, m.start() - 48):m.start()]
        if _CAP_NEGATORS.search(window):
            continue
        sub = m.group(1).lower()
        return sub, f"pkm {sub}"
    return None


def screen_capability_claim(draft: str) -> tuple[str, str | None]:
    """M4 capability-claim gate. Three verdicts:
      ("clean", None)         — surface present; no fabricated pkm invocation.
      ("violation", "pkm X")  — surface present; X is not a real subcommand.
      ("unavailable", marker) — ground-truth surface MISSING/unreadable (Ruling 2:
                                the gate NEVER silently no-ops). marker is the
                                unverifiable "pkm X" phrase if the draft made one,
                                else None. The caller WARN-logs every turn and, for a
                                marker'd claim, serves the honest-under-uncertainty
                                fallback rather than deliver an unverified claim.
    The caller regenerates once (violation) with the real surface grounded in, else
    serves the deterministic honest fallback."""
    text = draft or ""
    hit = _find_pkm_invocation(text)
    valid, _ = _pkm_surface()
    if not valid:
        return ("unavailable", hit[1] if hit else None)
    if hit and hit[0] not in valid:
        return ("violation", hit[1])
    return ("clean", None)


def capability_grounding_note(marker: str | None = None) -> str:
    """Corrective note for regeneration: grounds the model in the REAL pkm
    subcommand surface so it drops the invented command. Derived from the surface
    (no hand-kept list)."""
    _, primary = _pkm_surface()
    listed = ", ".join(primary) if primary else (
        "install, remove, list, search, info, update, upgrade, verify")
    named = f" (`{marker}` is not one of them)" if marker else ""
    return ("InterGenOS's package manager, pkm, has a FIXED set of subcommands and "
            f"no others{named}. The real subcommands are: {listed}. To install "
            "software the command is `pkm install <package>`. Correct your answer "
            "to use only real pkm subcommands, and if the user is asking about "
            "something pkm does not do (e.g. a hardware change), say so plainly "
            "instead of inventing a command.")


def honest_capability_fallback(marker: str | None = None) -> str:
    """Deterministic non-fabricating reply if the model still invents a pkm
    subcommand after one corrective regeneration. Honesty over helpfulness."""
    _, primary = _pkm_surface()
    listed = ", ".join(primary) if primary else (
        "install, remove, list, search, info, update, upgrade, verify")
    return ("To be accurate: InterGenOS's package manager is pkm, and it has no "
            f"such command. Its real subcommands are: {listed}. To install "
            "software, use `pkm install <package>`.")


def capability_unverified_fallback(marker: str | None = None) -> str:
    """Ruling 2 degraded path: the capability ground-truth surface
    (data/capability-surface.json) is missing, so a `pkm <subcommand>` claim could
    not be verified either way. Honest UNDER UNCERTAINTY — assert neither existence
    nor non-existence; point the user at the authoritative source."""
    cmd = marker or "that pkm command"
    return ("I can't verify InterGenOS's exact pkm command surface right now — my "
            f"capability reference isn't loaded — so I won't claim `{cmd}` works "
            "without checking. Please confirm with `pkm --help`, which lists the "
            "real subcommands.")


def answer_command_capability_question(token: str) -> tuple[str, str | None]:
    """M8 wave 4: answer a how-to / capability QUESTION that names a `pkm <token>`
    command, GROUNDED against the same M4 surface (data/capability-surface.json) the
    claim gate uses — never a hand-kept list, never a misparse into a fabricated
    `pkm install <token>`, never absorbed as a preference. This is the UPSTREAM
    companion to screen_capability_claim: the gate catches a fabricated subcommand in
    a DELIVERED draft, but a question like "how do I use pkm add" is misrouted (to the
    explain path, which invented `pkm install to`, or to memory, which absorbed it as
    "you prefer pkm audit") BEFORE any draft is screened. Answering the question here,
    from ground truth, kills the misparse at the source.

    Returns (status, answer):
      ("exists", None)      — token is a REAL subcommand/alias; the caller keeps its
                              own teaching/explain path (this leg changes nothing for
                              valid commands).
      ("absent", text)      — token is NOT a real subcommand (e.g. add, audit); the
                              honest answer names the real subcommands + `pkm install`
                              and says there is no such command. NEVER emits
                              `pkm install <token>`.
      ("unavailable", text) — the ground-truth surface is missing/unreadable (Ruling 2
                              fail-loud); honest under uncertainty, asserts nothing.
    """
    valid, primary = _pkm_surface()
    if not valid:
        return ("unavailable", capability_unverified_fallback(f"pkm {token}"))
    if token in valid:
        return ("exists", None)
    listed = ", ".join(primary)
    answer = (
        f"InterGenOS's package manager is pkm, and there's no `pkm {token}` command. "
        f"Its real subcommands are: {listed}. To install a package, use "
        "`pkm install <package>` (for example, `pkm install firefox`); to remove one, "
        "`pkm remove <package>`. See `pkm --help` for the full list.")
    return ("absent", answer)


def get_blocked_response(command: str) -> str:
    """Get a personality-infused blocked response for a dangerous command."""
    cmd = os.path.basename(command.strip().split()[0]) if command.strip() else ""

    # Check for prompt injection patterns
    if any(p in command.lower() for p in ["[system]", "ignore your", "new instructions",
                                           "you are now", "admin mode"]):
        return random.choice(_BLOCKED_RESPONSES["_injection"])

    # Check for fork bomb
    if ":()" in command or ":|:" in command:
        return random.choice(_BLOCKED_RESPONSES[":(){ :|:& };:"])

    # L2 anti-fabrication: wrong package manager -> redirect to pkm, echoing the
    # intended action/packages so the model (and user) sees the correct command.
    if cmd in WRONG_PKG_MANAGERS:
        toks = command.strip().split()
        verb = _PKM_VERB.get(toks[1].lower()) if len(toks) > 1 else None
        pkgs = [t for t in toks[2:] if not t.startswith("-")] if len(toks) > 2 else []
        if verb and pkgs:
            return f"This system uses pkm, not {cmd}. Try `pkm {verb} {' '.join(pkgs)}`."
        if verb:
            return f"This system uses pkm, not {cmd}. Try `pkm {verb}`."
        return (f"This system's package manager is pkm, not {cmd}. "
                "See `pkm --help` (install / remove / search / list / info).")

    # F-038: iproute2-netlink tools can't run in the hardened assistant — their
    # AF_NETLINK socket is denied, so executing one would crash the helper
    # (SIGSYS) rather than return anything. Redirect to a netlink-free source.
    if cmd in _NETLINK_COMMANDS:
        return (
            f"`{cmd}` isn't available to the hardened assistant — it needs a "
            "netlink socket the sandbox denies, so running it would crash the "
            "helper rather than answer. For interface and address info, read "
            "/sys/class/net (e.g. `ls /sys/class/net`, "
            "`cat /sys/class/net/<iface>/address`, "
            "`cat /sys/class/net/<iface>/operstate`), or run the command "
            "yourself in a terminal."
        )

    # Match by base command
    if cmd in _BLOCKED_RESPONSES:
        return random.choice(_BLOCKED_RESPONSES[cmd])

    return random.choice(_BLOCKED_RESPONSES["_default"])


def sanitize_output(output: str, max_lines: int = 200,
                    max_chars: int = 8000) -> str:
    """Sanitize command output for LLM consumption.

    Strips ANSI escape codes and truncates long output.
    """
    output = re.sub(r"\x1b\[[0-9;]*[a-zA-Z]", "", output)
    output = re.sub(r"\x1b\][^\x07]*\x07", "", output)

    lines = output.splitlines()
    if len(lines) > max_lines:
        output = "\n".join(lines[:max_lines])
        output += f"\n\n[Output truncated — {len(lines)} lines total, showing first {max_lines}]"

    if len(output) > max_chars:
        output = output[:max_chars]
        output += "\n\n[Output truncated at character limit]"

    return output
